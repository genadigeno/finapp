-- The disbursement to the borrower's wallet (path W) and the schedule it fixes (P11-TSK-014; PHASE_11_PLAN.md sections
-- 5.3, 7.1 T-dis, 7.2, 8, 12.2, 12.4 and 12.8, LENDING_LIFECYCLES.md sections 4.5, 4.6 and 4.11; ADR-0093, ADR-0096,
-- ADR-0097; INV-LND-07, INV-LND-01, INV-LND-03, INV-LND-13, INV-LED-01, INV-IDEM-01, INV-EVT-01, INV-LIFE-04).
--
-- The loan is born financially in ONE transaction (T-dis): under the party's credit profile lock (L0, through credit's
-- port), the loan's row lock (L3) and the disbursement's (L5), posting rule 1 - DR LOAN_PRINCIPAL P / CR CUSTOMER_WALLET
-- P - f, CR LOAN_FEE_INCOME f - through the ledger's PostingService under the key lending.disbursement:<loan>, and beside
-- it, in this order:
--
--     loan_disbursement  - PENDING -> POSTED, naming the journal entry by value (no cross-schema key, ADR-0029) and the
--                          entry's value date (the business date of the database clock in the pinned servicing zone,
--                          A10). Or PENDING -> FAILED with the cancellation's reason, nothing posted (rule 11).
--     loan               - PENDING_DISBURSEMENT -> ACTIVE beside its disbursement POSTED; -> CANCELLED beside it FAILED,
--                          with the same reason. The two commit together or not at all (two deferred checks).
--     accrual_start      - path W: interest runs from the disbursement entry's value date (ADR-0097 point 2). Path X's
--                          accrual start is the payout's conclusion (P11-TSK-015) - refused here until then.
--     repayment_schedule - schedule version 1, generated by the agreement's pinned schedule engine from the accrual start
--     loan_instalment      (ADR-0093): the schedule's header and its immutable projection rows. A deferred check holds the
--                          rows to the header at commit - n rows numbered 1..n that chain, the principal portions summing
--                          to P exactly and the interest to the total interest (INV-LND-03) - for every writer.
--
-- Why the loan's status and the posting must commit together: credit's exposure read (P11-TSK-013) counts a loan's
-- agreement principal while it is PENDING_DISBURSEMENT and its principal journal lines once it is not, in one statement;
-- an edge without its posting would be read as nothing, a posting without its edge as the principal twice. The capital
-- headroom (ADR-0096 section 5) moves the same principal from its committed term to its outstanding term in the same
-- commit - headroom does not move at disbursement.
--
-- Held for EVERY writer: the loan's replaced edge function (PENDING_DISBURSEMENT -> ACTIVE only beside the disbursement
-- POSTED, -> CANCELLED only beside it FAILED with the same reason, nothing else until -023/-026); the disbursement's
-- replaced edge function (identity frozen; a permit-only move; POSTED or FAILED only from PENDING while its loan still
-- awaits it; DISBURSEMENT_FAILED only once its deadline has passed on the database clock; the value date the business
-- date of this transaction in the pinned zone; path X refused until -015); the two deferred checks; accrual_start
-- UNIQUE (loan_id); repayment_schedule UNIQUE (loan_id, schedule_version) and version 1 only until -027; loan_instalment
-- UNIQUE (schedule_id, sequence); the conservation check; the new tables INSERT-only and never truncated.

-- ---------------------------------------------------------------------------------------------
-- The disbursement's outcome columns.
-- ---------------------------------------------------------------------------------------------
ALTER TABLE lending.loan_disbursement
    ADD COLUMN journal_entry_id uuid,
    ADD COLUMN value_date       date,
    ADD COLUMN decided_at       timestamptz,
    ADD COLUMN failure_reason   text;

ALTER TABLE lending.loan_disbursement
    -- POSTED exactly with its entry and value date.
    ADD CONSTRAINT loan_disbursement_posted_coherent CHECK (
        ((status = 'POSTED') = (journal_entry_id IS NOT NULL)) AND ((status = 'POSTED') = (value_date IS NOT NULL))),
    -- FAILED exactly with its reason - CancellationReason, the loan's own.
    ADD CONSTRAINT loan_disbursement_failed_coherent CHECK ((status = 'FAILED') = (failure_reason IS NOT NULL)),
    ADD CONSTRAINT loan_disbursement_failure_reason_is_known CHECK (
        failure_reason IS NULL OR failure_reason IN ('STANDING_LOST', 'DISBURSEMENT_FAILED')),
    -- Decided exactly when terminal.
    ADD CONSTRAINT loan_disbursement_decided_coherent CHECK ((status <> 'PENDING') = (decided_at IS NOT NULL)),
    -- One disbursement per journal entry (INV-LND-07): the ledger key gives one entry per loan, this one row per entry.
    ADD CONSTRAINT loan_disbursement_entry_unique UNIQUE (journal_entry_id);

-- The disbursement sweep's claim: path W's PENDING disbursements by permit (path X's are P11-TSK-015's).
CREATE INDEX loan_disbursement_due ON lending.loan_disbursement (next_attempt_at, id)
    WHERE status = 'PENDING' AND payout_method_id IS NULL;
-- The oldest PENDING disbursement, for finapp.lending.disbursement.pending.age.
CREATE INDEX loan_disbursement_pending ON lending.loan_disbursement (created_at) WHERE status = 'PENDING';

COMMENT ON TABLE lending.loan_disbursement IS
    'An instalment loan''s disbursement (P11-TSK-012 births it, P11-TSK-014 moves it; LENDING_LIFECYCLES.md section 4.6): born PENDING beside its loan PENDING_DISBURSEMENT, its deadline (the pinned terms version''s disbursement deadline) and its permit stamped by the database; the customer''s verified payout method present exactly for path X - an opaque payments reference, never an account identifier (INV-RAIL-03). PENDING -> POSTED (the journal entry of posting rule 1 named by value, its value date) beside the loan''s ACTIVE edge, or PENDING -> FAILED (STANDING_LOST at once, DISBURSEMENT_FAILED only once the deadline passed) beside its CANCELLED edge - in one transaction. One per loan, one per journal entry.';

-- The pinned servicing zone's business date of an instant (A2, A10): the zone is UTC or a fixed offset +HH:MM / -HH:MM
-- (LoanTerms' canonical form), read here as an interval - never through AT TIME ZONE's POSIX sign convention.
CREATE OR REPLACE FUNCTION lending.business_date(instant timestamptz, servicing_zone text)
    RETURNS date
    LANGUAGE sql
    STABLE
AS $$
    SELECT ((instant AT TIME ZONE 'UTC')
            + CASE WHEN servicing_zone = 'UTC' THEN interval '0' ELSE CAST(servicing_zone AS interval) END)::date
$$;

CREATE OR REPLACE FUNCTION lending.loan_disbursement_permits_only_machine_edges()
    RETURNS trigger
    LANGUAGE plpgsql
AS $$
DECLARE
    deadline_hours integer;
    preference text;
    loan_status text;
    zone text;
BEGIN
    IF TG_OP = 'INSERT' THEN
        IF NEW.status <> 'PENDING' THEN
            RAISE EXCEPTION 'a disbursement is born PENDING (P11-TSK-012)';
        END IF;
        -- Beside its instalment loan awaiting disbursement; the deadline is its agreement's pinned terms version's.
        SELECT t.disbursement_deadline_hours, a.payout_preference INTO deadline_hours, preference
          FROM lending.loan l
          JOIN lending.loan_offer o ON o.id = l.offer_id
          JOIN lending.loan_application a ON a.id = o.application_id
          JOIN lending.loan_terms t ON t.terms_version_id = o.terms_version_id
         WHERE l.id = NEW.loan_id AND l.kind = 'INSTALMENT' AND l.status = 'PENDING_DISBURSEMENT';
        IF NOT FOUND OR deadline_hours IS NULL THEN
            RAISE EXCEPTION 'a disbursement is born beside its instalment loan PENDING_DISBURSEMENT (P11-TSK-012)';
        END IF;
        -- Path X exactly when the application preferred an external account (A25; ADR-0097).
        IF (preference = 'EXTERNAL_ACCOUNT') <> (NEW.payout_method_id IS NOT NULL) THEN
            RAISE EXCEPTION 'a disbursement names a payout method exactly when its application preferred an external account (P11-TSK-012)';
        END IF;
        NEW.created_at := statement_timestamp();
        NEW.deadline_at := statement_timestamp() + make_interval(hours => deadline_hours);
        -- Due for the disbursement sweep at once (P11-TSK-014).
        NEW.next_attempt_at := statement_timestamp();
        RETURN NEW;
    END IF;
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'a disbursement is never deleted (P11-TSK-012, INV-HIST-01)';
    END IF;
    IF NEW.id IS DISTINCT FROM OLD.id OR NEW.loan_id IS DISTINCT FROM OLD.loan_id
            OR NEW.payout_method_id IS DISTINCT FROM OLD.payout_method_id
            OR NEW.created_at IS DISTINCT FROM OLD.created_at OR NEW.deadline_at IS DISTINCT FROM OLD.deadline_at
            OR NEW.correlation_id IS DISTINCT FROM OLD.correlation_id THEN
        RAISE EXCEPTION 'a disbursement''s identity, path, birth and deadline are frozen (P11-TSK-014)';
    END IF;
    IF OLD.status <> 'PENDING' THEN
        RAISE EXCEPTION 'a % disbursement is terminal (P11-TSK-014, INV-LIFE-04)', OLD.status;
    END IF;
    -- A permit-only move: the sweep's claim re-stamps the permit and nothing else.
    IF NEW.status = 'PENDING' THEN
        IF NEW.next_attempt_at IS NOT DISTINCT FROM OLD.next_attempt_at OR NEW.journal_entry_id IS NOT NULL
                OR NEW.value_date IS NOT NULL OR NEW.failure_reason IS NOT NULL OR NEW.decided_at IS NOT NULL THEN
            RAISE EXCEPTION 'a PENDING disbursement moves its permit and nothing else (P11-TSK-014)';
        END IF;
        RETURN NEW;
    END IF;
    -- PENDING -> POSTED | FAILED, while its loan still awaits it: the loan moves beside it, in this transaction, and the
    -- deferred check below holds the pair at commit.
    SELECT l.status, t.servicing_zone INTO loan_status, zone
      FROM lending.loan l
      JOIN lending.loan_offer o ON o.id = l.offer_id
      JOIN lending.loan_terms t ON t.terms_version_id = o.terms_version_id
     WHERE l.id = OLD.loan_id;
    IF loan_status IS DISTINCT FROM 'PENDING_DISBURSEMENT' THEN
        RAISE EXCEPTION 'a disbursement is decided only while its loan is PENDING_DISBURSEMENT (P11-TSK-014, INV-LND-07)';
    END IF;
    NEW.next_attempt_at := OLD.next_attempt_at;
    NEW.decided_at := statement_timestamp();
    IF NEW.status = 'POSTED' THEN
        -- Path X posts beside its payout's hold (P11-TSK-015); until then only the wallet path posts.
        IF OLD.payout_method_id IS NOT NULL THEN
            RAISE EXCEPTION 'a path X disbursement is not posted until P11-TSK-015 admits its payout';
        END IF;
        IF NEW.journal_entry_id IS NULL OR NEW.value_date IS NULL OR NEW.failure_reason IS NOT NULL THEN
            RAISE EXCEPTION 'a POSTED disbursement names its journal entry and value date, and no failure (P11-TSK-014)';
        END IF;
        -- The value date is this transaction's business date in the pinned servicing zone (A10, INV-LND-10): read by the
        -- step after its locks, so between the transaction's start and this statement.
        IF NEW.value_date < lending.business_date(transaction_timestamp(), zone)
                OR NEW.value_date > lending.business_date(statement_timestamp(), zone) THEN
            RAISE EXCEPTION 'a disbursement''s value date is the business date of the database clock in its pinned zone (P11-TSK-014, A10)';
        END IF;
    ELSIF NEW.status = 'FAILED' THEN
        IF NEW.journal_entry_id IS NOT NULL OR NEW.value_date IS NOT NULL OR NEW.failure_reason IS NULL THEN
            RAISE EXCEPTION 'a FAILED disbursement names its reason and posted nothing (P11-TSK-014, rule 11)';
        END IF;
        -- A wallet that cannot be posted is retried until the deadline: the failure is judged on the database clock.
        IF NEW.failure_reason = 'DISBURSEMENT_FAILED' AND OLD.deadline_at > statement_timestamp() THEN
            RAISE EXCEPTION 'a disbursement fails only once its deadline has passed on the database clock (P11-TSK-014)';
        END IF;
    ELSE
        RAISE EXCEPTION 'a disbursement moves PENDING -> POSTED | FAILED; % -> % is not an edge (P11-TSK-014)', OLD.status, NEW.status;
    END IF;
    RETURN NEW;
END;
$$;

-- ---------------------------------------------------------------------------------------------
-- The loan's edge function, replaced: PENDING_DISBURSEMENT -> ACTIVE | CANCELLED admitted, beside the disbursement.
-- ---------------------------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION lending.loan_permits_only_machine_edges()
    RETURNS trigger
    LANGUAGE plpgsql
AS $$
DECLARE
    offer lending.loan_offer%ROWTYPE;
    offered_currency char(3);
    disbursement lending.loan_disbursement%ROWTYPE;
BEGIN
    IF TG_OP = 'INSERT' THEN
        -- Born by kind (LENDING_LIFECYCLES.md section 4.5): a loan awaits its disbursement, a line is born serviceable.
        IF NEW.closed_at IS NOT NULL OR NEW.closure_reason IS NOT NULL OR NEW.cancellation_reason IS NOT NULL
                OR NOT ((NEW.kind = 'INSTALMENT' AND NEW.status = 'PENDING_DISBURSEMENT')
                        OR (NEW.kind = 'REVOLVING' AND NEW.status = 'ACTIVE')) THEN
            RAISE EXCEPTION 'a loan is born PENDING_DISBURSEMENT, a credit line ACTIVE, and open (P11-TSK-012)';
        END IF;
        -- Born under its offer's row lock (L2), for its own party's OFFERED, unexpired offer of the same product, on its
        -- decision, in its currency - the offer moves ACCEPTED in the same transaction.
        SELECT * INTO offer FROM lending.loan_offer o WHERE o.id = NEW.offer_id;
        IF NOT FOUND OR offer.status <> 'OFFERED' OR offer.expires_at <= statement_timestamp()
                OR offer.party_id <> NEW.party_id OR offer.product <> NEW.product
                OR offer.decision_id <> NEW.decision_id THEN
            RAISE EXCEPTION 'a loan is born for its own party''s OFFERED, unexpired offer of the same product, on its decision (P11-TSK-012)';
        END IF;
        SELECT t.currency INTO offered_currency FROM lending.loan_offer_terms t WHERE t.offer_id = NEW.offer_id;
        IF offered_currency IS DISTINCT FROM NEW.currency THEN
            RAISE EXCEPTION 'a loan is held in its offer''s currency (P11-TSK-012)';
        END IF;
        NEW.opened_at := statement_timestamp();
        RETURN NEW;
    END IF;
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'a loan is never deleted (P11-TSK-012, INV-HIST-01)';
    END IF;
    IF NEW.id IS DISTINCT FROM OLD.id OR NEW.party_id IS DISTINCT FROM OLD.party_id
            OR NEW.product IS DISTINCT FROM OLD.product OR NEW.kind IS DISTINCT FROM OLD.kind
            OR NEW.currency IS DISTINCT FROM OLD.currency OR NEW.offer_id IS DISTINCT FROM OLD.offer_id
            OR NEW.decision_id IS DISTINCT FROM OLD.decision_id OR NEW.opened_at IS DISTINCT FROM OLD.opened_at
            OR NEW.correlation_id IS DISTINCT FROM OLD.correlation_id THEN
        RAISE EXCEPTION 'a loan''s identity, kind, currency and origin are frozen from birth (P11-TSK-012)';
    END IF;
    -- The disbursement's two edges (P11-TSK-014): each beside the disbursement's matching state, in its transaction.
    IF OLD.status = 'PENDING_DISBURSEMENT' AND NEW.status IN ('ACTIVE', 'CANCELLED') THEN
        SELECT * INTO disbursement FROM lending.loan_disbursement d WHERE d.loan_id = OLD.id;
        IF NEW.status = 'ACTIVE' THEN
            IF NOT FOUND OR disbursement.status <> 'POSTED' OR NEW.closed_at IS NOT NULL
                    OR NEW.closure_reason IS NOT NULL OR NEW.cancellation_reason IS NOT NULL THEN
                RAISE EXCEPTION 'a loan is ACTIVE only beside its disbursement POSTED (P11-TSK-014, INV-LND-07)';
            END IF;
        ELSE
            IF NOT FOUND OR disbursement.status <> 'FAILED' OR NEW.closure_reason IS NOT NULL
                    OR NEW.cancellation_reason IS DISTINCT FROM disbursement.failure_reason THEN
                RAISE EXCEPTION 'a loan is CANCELLED only beside its disbursement FAILED, for the same reason (P11-TSK-014)';
            END IF;
            NEW.closed_at := statement_timestamp();
        END IF;
        RETURN NEW;
    END IF;
    -- Every other edge is a later task's: a line's closure request (P11-TSK-023), the closure (P11-TSK-026) - each
    -- replaces this function and admits its edge beside its own fact. Out of CANCELLED nothing, ever (INV-LIFE-04);
    -- ACTIVE -> CANCELLED and ACTIVE -> PENDING_DISBURSEMENT never (LENDING_LIFECYCLES.md section 4.5).
    RAISE EXCEPTION 'a loan does not move here; % -> % is not an edge until its task admits it (P11-TSK-014)', OLD.status, NEW.status;
END;
$$;

-- ---------------------------------------------------------------------------------------------
-- The accrual start: when interest runs from (born once per loan).
-- ---------------------------------------------------------------------------------------------
CREATE TABLE lending.accrual_start (
    id                uuid        NOT NULL,
    loan_id           uuid        NOT NULL,
    start_date        date        NOT NULL,
    origin            text        NOT NULL,
    journal_entry_id  uuid,
    created_at        timestamptz NOT NULL,
    correlation_id    text        NOT NULL,
    CONSTRAINT accrual_start_pk PRIMARY KEY (id),
    -- One accrual start per loan (LENDING_LIFECYCLES.md section 4.11).
    CONSTRAINT accrual_start_loan_unique UNIQUE (loan_id),
    CONSTRAINT accrual_start_loan_fk FOREIGN KEY (loan_id) REFERENCES lending.loan (id),
    -- Path W: the disbursement entry's value date; path X: the payout's conclusion (P11-TSK-015).
    CONSTRAINT accrual_start_origin_is_known CHECK (origin IN ('DISBURSEMENT', 'PAYOUT_CONCLUDED')),
    CONSTRAINT accrual_start_disbursement_names_its_entry CHECK ((origin = 'DISBURSEMENT') = (journal_entry_id IS NOT NULL)),
    CONSTRAINT accrual_start_correlation_bounded CHECK (char_length(correlation_id) BETWEEN 1 AND 200)
);

COMMENT ON TABLE lending.accrual_start IS
    'When an instalment loan''s interest runs from (P11-TSK-014, ADR-0097 points 2 and 7, LENDING_LIFECYCLES.md section 4.11): path W - born in the disbursement''s transaction, the disbursement entry''s value date; path X - the payout''s conclusion (P11-TSK-015). One per loan, INSERT-only for every role. The schedule''s first period starts here.';

CREATE OR REPLACE FUNCTION lending.accrual_start_is_born_once()
    RETURNS trigger
    LANGUAGE plpgsql
AS $$
DECLARE
    disbursement lending.loan_disbursement%ROWTYPE;
BEGIN
    IF TG_OP <> 'INSERT' THEN
        RAISE EXCEPTION 'an accrual start is immutable from insert, for every role (P11-TSK-014)';
    END IF;
    IF NEW.origin <> 'DISBURSEMENT' THEN
        RAISE EXCEPTION 'a payout''s accrual start is not admitted until P11-TSK-015';
    END IF;
    -- Path W: beside its instalment loan ACTIVE and its wallet disbursement POSTED, on that entry's value date.
    SELECT d.* INTO disbursement
      FROM lending.loan_disbursement d JOIN lending.loan l ON l.id = d.loan_id
     WHERE d.loan_id = NEW.loan_id AND l.kind = 'INSTALMENT' AND l.status = 'ACTIVE';
    IF NOT FOUND OR disbursement.status <> 'POSTED' OR disbursement.payout_method_id IS NOT NULL
            OR NEW.start_date <> disbursement.value_date
            OR NEW.journal_entry_id IS DISTINCT FROM disbursement.journal_entry_id THEN
        RAISE EXCEPTION 'a wallet disbursement''s accrual start is its entry''s value date, beside the loan ACTIVE (P11-TSK-014, ADR-0097)';
    END IF;
    NEW.created_at := statement_timestamp();
    RETURN NEW;
END;
$$;

CREATE TRIGGER accrual_start_is_born_once
    BEFORE INSERT OR UPDATE OR DELETE ON lending.accrual_start
    FOR EACH ROW
    EXECUTE FUNCTION lending.accrual_start_is_born_once();

CREATE TRIGGER accrual_start_is_never_truncated
    BEFORE TRUNCATE ON lending.accrual_start
    FOR EACH STATEMENT
    EXECUTE FUNCTION lending.loan_is_never_truncated();

-- ---------------------------------------------------------------------------------------------
-- The schedule: a version's header and its immutable projection rows.
-- ---------------------------------------------------------------------------------------------
CREATE TABLE lending.repayment_schedule (
    id                       uuid        NOT NULL,
    loan_id                  uuid        NOT NULL,
    schedule_version         integer     NOT NULL,
    agreement_id             uuid        NOT NULL,
    agreement_version        integer     NOT NULL,
    schedule_engine_version  smallint    NOT NULL,
    currency                 char(3)     NOT NULL,
    scale                    smallint    NOT NULL,
    principal_minor          bigint      NOT NULL,
    instalment_minor         bigint      NOT NULL,
    final_instalment_minor   bigint      NOT NULL,
    total_interest_minor     bigint      NOT NULL,
    term_months              smallint    NOT NULL,
    start_date               date        NOT NULL,
    intended_day             smallint    NOT NULL,
    created_at               timestamptz NOT NULL,
    correlation_id           text        NOT NULL,
    CONSTRAINT repayment_schedule_pk PRIMARY KEY (id),
    -- One schedule per version per loan: duplicate generation is one schedule (PHASE_11_PLAN.md section 7.4).
    CONSTRAINT repayment_schedule_version_unique UNIQUE (loan_id, schedule_version),
    CONSTRAINT repayment_schedule_loan_fk FOREIGN KEY (loan_id) REFERENCES lending.loan (id),
    CONSTRAINT repayment_schedule_agreement_fk FOREIGN KEY (agreement_id) REFERENCES lending.loan_agreement (id),
    CONSTRAINT repayment_schedule_versions_numbered CHECK (
        schedule_version >= 1 AND agreement_version >= 1 AND schedule_engine_version >= 1),
    CONSTRAINT repayment_schedule_currency_is_the_products CHECK (currency = 'EUR' AND scale BETWEEN 0 AND 9),
    -- A positive principal amortised by level instalments, the final one never larger (ADR-0093).
    CONSTRAINT repayment_schedule_amounts_shape CHECK (
        principal_minor > 0 AND instalment_minor > 0 AND final_instalment_minor > 0
        AND final_instalment_minor <= instalment_minor AND total_interest_minor >= 0),
    CONSTRAINT repayment_schedule_term_and_day CHECK (term_months >= 1 AND intended_day BETWEEN 1 AND 31),
    CONSTRAINT repayment_schedule_correlation_bounded CHECK (char_length(correlation_id) BETWEEN 1 AND 200)
);

COMMENT ON TABLE lending.repayment_schedule IS
    'A loan''s schedule versions (P11-TSK-014 births version 1; ADR-0093, PHASE_11_PLAN.md section 12.2): the projection of an agreement version by its pinned schedule engine from the accrual start - the principal, the level and final instalments, the total interest, the term, the start and the intended day; its periods are loan_instalment rows. Named for the agreement version and the schedule engine version, so it is re-derivable. Version 1 here; later versions are an accepted change''s (P11-TSK-027). INSERT-only for every role; a deferred check holds its rows to it (INV-LND-03). The projection, not the bill (billing is P11-TSK-017''s). RESTRICTED-FINANCIAL.';

CREATE OR REPLACE FUNCTION lending.repayment_schedule_is_born_once()
    RETURNS trigger
    LANGUAGE plpgsql
AS $$
DECLARE
    agreement lending.loan_agreement%ROWTYPE;
    started date;
BEGIN
    IF TG_OP <> 'INSERT' THEN
        RAISE EXCEPTION 'a schedule version is immutable from insert, for every role (P11-TSK-014, INV-LND-03)';
    END IF;
    IF NEW.schedule_version <> 1 THEN
        RAISE EXCEPTION 'a schedule version after the first is an accepted change''s - not admitted until P11-TSK-027';
    END IF;
    -- Version 1: the loan's agreement version 1, by its pinned engine, from the loan's accrual start, while ACTIVE.
    SELECT a.* INTO agreement
      FROM lending.loan_agreement a JOIN lending.loan l ON l.id = a.loan_id
     WHERE a.id = NEW.agreement_id AND a.loan_id = NEW.loan_id AND a.version = 1
       AND l.kind = 'INSTALMENT' AND l.status = 'ACTIVE';
    SELECT s.start_date INTO started FROM lending.accrual_start s WHERE s.loan_id = NEW.loan_id;
    IF agreement.id IS NULL OR started IS NULL OR NEW.agreement_version <> 1
            OR NEW.schedule_engine_version IS DISTINCT FROM agreement.schedule_engine_version
            OR NEW.currency <> agreement.currency OR NEW.scale <> agreement.scale
            OR NEW.principal_minor <> agreement.amount_minor
            OR NEW.term_months IS DISTINCT FROM agreement.term_months
            OR NEW.intended_day <> agreement.repayment_day
            OR NEW.start_date <> started THEN
        RAISE EXCEPTION 'schedule version 1 projects its loan''s agreement version 1 by the pinned engine from the accrual start (P11-TSK-014, ADR-0093)';
    END IF;
    NEW.created_at := statement_timestamp();
    RETURN NEW;
END;
$$;

CREATE TRIGGER repayment_schedule_is_born_once
    BEFORE INSERT OR UPDATE OR DELETE ON lending.repayment_schedule
    FOR EACH ROW
    EXECUTE FUNCTION lending.repayment_schedule_is_born_once();

CREATE TRIGGER repayment_schedule_is_never_truncated
    BEFORE TRUNCATE ON lending.repayment_schedule
    FOR EACH STATEMENT
    EXECUTE FUNCTION lending.loan_is_never_truncated();

CREATE TABLE lending.loan_instalment (
    id                       uuid     NOT NULL,
    schedule_id              uuid     NOT NULL,
    loan_id                  uuid     NOT NULL,
    sequence                 smallint NOT NULL,
    period_start             date     NOT NULL,
    due_date                 date     NOT NULL,
    days                     integer  NOT NULL,
    currency                 char(3)  NOT NULL,
    scale                    smallint NOT NULL,
    opening_principal_minor  bigint   NOT NULL,
    interest_minor           bigint   NOT NULL,
    principal_minor          bigint   NOT NULL,
    amount_minor             bigint   NOT NULL,
    closing_principal_minor  bigint   NOT NULL,
    CONSTRAINT loan_instalment_pk PRIMARY KEY (id),
    CONSTRAINT loan_instalment_sequence_unique UNIQUE (schedule_id, sequence),
    CONSTRAINT loan_instalment_schedule_fk FOREIGN KEY (schedule_id) REFERENCES lending.repayment_schedule (id),
    CONSTRAINT loan_instalment_loan_fk FOREIGN KEY (loan_id) REFERENCES lending.loan (id),
    CONSTRAINT loan_instalment_currency_is_the_products CHECK (currency = 'EUR' AND scale BETWEEN 0 AND 9),
    -- One period judged in itself (SchedulePeriod): its days actual (ACT/365F), its amount its parts, its closing the
    -- opening less the principal portion, which is positive.
    CONSTRAINT loan_instalment_period_shape CHECK (
        sequence >= 1 AND due_date > period_start AND days = due_date - period_start),
    CONSTRAINT loan_instalment_amounts_shape CHECK (
        interest_minor >= 0 AND principal_minor > 0 AND amount_minor = interest_minor + principal_minor
        AND closing_principal_minor = opening_principal_minor - principal_minor AND closing_principal_minor >= 0)
);

CREATE INDEX loan_instalment_by_loan ON lending.loan_instalment (loan_id, due_date);

COMMENT ON TABLE lending.loan_instalment IS
    'A schedule version''s periods (P11-TSK-014; ADR-0093, SchedulePeriod): the period''s start and due date, its actual days, the opening principal, the period''s interest, the principal portion, the instalment and the closing principal. Immutable projection rows, INSERT-only for every role, held to their schedule at commit (n rows numbered 1..n that chain, conserving principal exactly - INV-LND-03). RESTRICTED-FINANCIAL.';

CREATE OR REPLACE FUNCTION lending.loan_instalment_is_born_once()
    RETURNS trigger
    LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP <> 'INSERT' THEN
        RAISE EXCEPTION 'an instalment is immutable from insert, for every role (P11-TSK-014, INV-LND-03)';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM lending.repayment_schedule s
                    WHERE s.id = NEW.schedule_id AND s.loan_id = NEW.loan_id
                      AND s.currency = NEW.currency AND s.scale = NEW.scale) THEN
        RAISE EXCEPTION 'an instalment belongs to its own loan''s schedule, in its currency and scale (P11-TSK-014)';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER loan_instalment_is_born_once
    BEFORE INSERT OR UPDATE OR DELETE ON lending.loan_instalment
    FOR EACH ROW
    EXECUTE FUNCTION lending.loan_instalment_is_born_once();

CREATE TRIGGER loan_instalment_is_never_truncated
    BEFORE TRUNCATE ON lending.loan_instalment
    FOR EACH STATEMENT
    EXECUTE FUNCTION lending.loan_is_never_truncated();

-- The conservation check (INV-LND-03), at commit, for every writer: the schedule's rows are exactly n, numbered 1..n,
-- the first opening on the principal from the start date, each starting where its predecessor fell due and opening on
-- its closing, the last closing at zero; every instalment the level one but the last, which is the final; the principal
-- portions sum to the principal and the interest to the total interest (so the instalments sum to both). Run when the
-- schedule is born and again for every row added to it - a row added to a committed schedule breaks its count. The sums
-- are exact (bigint into numeric): a verification, never a figure anyone is charged.
CREATE OR REPLACE FUNCTION lending.repayment_schedule_conserves(schedule uuid)
    RETURNS void
    LANGUAGE plpgsql
AS $$
DECLARE
    header lending.repayment_schedule%ROWTYPE;
    rows_count integer;
    first_sequence integer;
    last_sequence integer;
    principal_sum numeric;
    interest_sum numeric;
BEGIN
    SELECT * INTO header FROM lending.repayment_schedule s WHERE s.id = schedule;
    SELECT count(*), min(i.sequence), max(i.sequence), sum(i.principal_minor), sum(i.interest_minor)
      INTO rows_count, first_sequence, last_sequence, principal_sum, interest_sum
      FROM lending.loan_instalment i WHERE i.schedule_id = schedule;
    IF rows_count IS DISTINCT FROM header.term_months::integer OR first_sequence IS DISTINCT FROM 1
            OR last_sequence IS DISTINCT FROM header.term_months::integer
            OR principal_sum IS DISTINCT FROM header.principal_minor::numeric
            OR interest_sum IS DISTINCT FROM header.total_interest_minor::numeric THEN
        RAISE EXCEPTION 'a schedule''s instalments are n periods numbered 1..n whose principal sums to its principal and interest to its total interest (P11-TSK-014, INV-LND-03)';
    END IF;
    IF EXISTS (SELECT 1 FROM lending.loan_instalment i
                WHERE i.schedule_id = schedule AND i.sequence = 1
                  AND (i.period_start <> header.start_date OR i.opening_principal_minor <> header.principal_minor))
            OR EXISTS (SELECT 1 FROM lending.loan_instalment i
                        JOIN lending.loan_instalment p ON p.schedule_id = i.schedule_id AND p.sequence = i.sequence - 1
                       WHERE i.schedule_id = schedule
                         AND (i.period_start <> p.due_date OR i.opening_principal_minor <> p.closing_principal_minor))
            OR EXISTS (SELECT 1 FROM lending.loan_instalment i
                        WHERE i.schedule_id = schedule
                          AND ((i.sequence < header.term_months AND i.amount_minor <> header.instalment_minor)
                               OR (i.sequence = header.term_months
                                   AND (i.amount_minor <> header.final_instalment_minor
                                        OR i.closing_principal_minor <> 0)))) THEN
        RAISE EXCEPTION 'a schedule''s periods chain from its start and principal, level instalments then the final, closing at zero (P11-TSK-014, INV-LND-03)';
    END IF;
END;
$$;

CREATE OR REPLACE FUNCTION lending.repayment_schedule_conserves_at_commit()
    RETURNS trigger
    LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_TABLE_NAME = 'repayment_schedule' THEN
        PERFORM lending.repayment_schedule_conserves(NEW.id);
    ELSE
        PERFORM lending.repayment_schedule_conserves(NEW.schedule_id);
    END IF;
    RETURN NULL;
END;
$$;

CREATE CONSTRAINT TRIGGER repayment_schedule_conserves
    AFTER INSERT ON lending.repayment_schedule
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW
    EXECUTE FUNCTION lending.repayment_schedule_conserves_at_commit();

CREATE CONSTRAINT TRIGGER loan_instalment_conserves
    AFTER INSERT ON lending.loan_instalment
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW
    EXECUTE FUNCTION lending.repayment_schedule_conserves_at_commit();

-- ---------------------------------------------------------------------------------------------
-- The two deferred checks: the loan's edge and the disbursement's commit together, with path W's facts.
-- ---------------------------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION lending.loan_disbursement_decided_beside_its_loan()
    RETURNS trigger
    LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.status = 'POSTED'
            AND NOT EXISTS (SELECT 1 FROM lending.loan l WHERE l.id = NEW.loan_id AND l.status = 'ACTIVE') THEN
        RAISE EXCEPTION 'a disbursement committed POSTED without its loan ACTIVE (P11-TSK-014, INV-LND-07)';
    END IF;
    IF NEW.status = 'FAILED'
            AND NOT EXISTS (SELECT 1 FROM lending.loan l WHERE l.id = NEW.loan_id AND l.status = 'CANCELLED'
                              AND l.cancellation_reason = NEW.failure_reason) THEN
        RAISE EXCEPTION 'a disbursement committed FAILED without its loan CANCELLED for the same reason (P11-TSK-014)';
    END IF;
    RETURN NULL;
END;
$$;

CREATE CONSTRAINT TRIGGER loan_disbursement_decided_beside_its_loan
    AFTER UPDATE ON lending.loan_disbursement
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW
    WHEN (NEW.status IS DISTINCT FROM OLD.status)
    EXECUTE FUNCTION lending.loan_disbursement_decided_beside_its_loan();

CREATE OR REPLACE FUNCTION lending.loan_disbursed_beside_its_facts()
    RETURNS trigger
    LANGUAGE plpgsql
AS $$
DECLARE
    disbursement lending.loan_disbursement%ROWTYPE;
BEGIN
    SELECT * INTO disbursement FROM lending.loan_disbursement d WHERE d.loan_id = NEW.id;
    IF NOT FOUND OR disbursement.status <> 'POSTED' THEN
        RAISE EXCEPTION 'a loan committed ACTIVE without its disbursement POSTED (P11-TSK-014, INV-LND-07)';
    END IF;
    -- Path W: the accrual start and schedule version 1 in the same transaction (ADR-0097 point 2).
    IF disbursement.payout_method_id IS NULL
            AND (NOT EXISTS (SELECT 1 FROM lending.accrual_start s WHERE s.loan_id = NEW.id)
                 OR NOT EXISTS (SELECT 1 FROM lending.repayment_schedule r
                                 WHERE r.loan_id = NEW.id AND r.schedule_version = 1)) THEN
        RAISE EXCEPTION 'a wallet-disbursed loan committed ACTIVE without its accrual start and schedule version 1 (P11-TSK-014, ADR-0097)';
    END IF;
    RETURN NULL;
END;
$$;

CREATE CONSTRAINT TRIGGER loan_disbursed_beside_its_facts
    AFTER UPDATE ON lending.loan
    DEFERRABLE INITIALLY DEFERRED
    FOR EACH ROW
    WHEN (OLD.status = 'PENDING_DISBURSEMENT' AND NEW.status = 'ACTIVE')
    EXECUTE FUNCTION lending.loan_disbursed_beside_its_facts();

