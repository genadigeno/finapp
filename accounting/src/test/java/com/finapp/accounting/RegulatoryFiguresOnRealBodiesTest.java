/**
 * A figure path over <strong>the bodies the real definitions write</strong> (`P14-TSK-018`; `P14-TSK-016`'s routed note; {@code INV-ACC-13}): {@code BALANCE_SHEET}'s, {@code INCOME_STATEMENT}'s and {@code TRIAL_BALANCE}'s, generated and read back as issued, so a form line's grammar is held to the content a
 * FINAL run really carries and not to a suite's idea of it. A definition's change of shape fails here before a form silently loses a line. Over {@code StatementRunsTest}'s books: in memory, generated by the real {@link ReportGeneration}.
 */
@DisplayName("a figure path over what the real definitions write (P14-TSK-018)")
class RegulatoryFiguresOnRealBodiesTest {

    private static final IdGenerator IDS = new IdGenerator(Clock.systemUTC(), new SecureRandom());
    private static final Connection UOW = (Connection) Proxy.newProxyInstance(Connection.class.getClassLoader(), new Class<?>[] {Connection.class}, (proxy, method, args) -> {
        throw new UnsupportedOperationException("the in-memory stores never touch the connection");
    });
    private static final YearMonth FEBRUARY = YearMonth.of(2096, 2);
    private static final Actor ACCOUNTANT = new Actor("accountant-1", ActorType.CUSTOMER);
    private static final String CASH = "CASH_AT_BANK/OPERATIONAL";
    private static final String WALLET = "CUSTOMER_WALLET/CUSTOMER";

    private final ReportRunsTest.MovableClock clock = new ReportRunsTest.MovableClock(Instant.parse("2096-03-10T09:00:00Z"));
    private final InMemoryAccountingPeriodStore periodStore = new InMemoryAccountingPeriodStore();
    private final InMemoryGlMappingStore mappings = new InMemoryGlMappingStore();
    private final InMemoryReportRunStore store = new InMemoryReportRunStore(clock, periodStore);
    private final InMemoryTrialBalanceReads books = new InMemoryTrialBalanceReads();
    private final ValuationRateReads rates = (snapshot, id) -> Optional.empty();
    private final ReportGeneration generation = new ReportGeneration((snapshot, id) -> periodStore.find(snapshot, id).map(row -> new ReportGeneration.PeriodState(row.status(), row.lockedAt())), Duration.ofMinutes(4), () -> 0L);
    private GlMappingVersionId version;
    private AccountingPeriodId february;
    private ReportDefinition sheet;
    private ReportDefinition income;
    private ReportDefinition trialBalance;

    @BeforeEach
    void februaryClosed() {
        version = GlMappingVersionId.next(IDS);
        mappings.insertProposal(UOW, new GlMappingStore.NewProposal(version, 1, ReferenceGlMapping.version(YearMonth.of(2096, 1)), new Actor("proposer", ActorType.CUSTOMER), "the reference chart", correlation(), UUID.randomUUID()));
        mappings.decide(UOW, version, GlMappingVersionStatus.ACTIVE, new Actor("approver", ActorType.CUSTOMER), "ok");
        february = AccountingPeriodId.next(IDS);
        periodStore.insertIfAbsent(UOW, new AccountingPeriodStore.NewPeriod(february, FEBRUARY, correlation()));
        books.version(version, mappings.content(UOW, version));
        books.period(new TrialBalanceReads.Period(february, FEBRUARY.atDay(1), FEBRUARY.atEndOfMonth(), PeriodStatus.OPEN, Optional.empty()));
        books.post(FEBRUARY.atDay(3), clock.instant().minusSeconds(86_400), "EUR", 2, 2_500, CASH, WALLET);
        books.post(FEBRUARY.atDay(4), clock.instant().minusSeconds(86_400), "USD", 2, 1_001, CASH, WALLET);
        StatementNotes notes = new StatementNotes((snapshot, period) -> new SuspenseAsOfCutoff.Register(period.atEndOfMonth(), Instant.EPOCH, List.of()),
                (snapshot, period) -> new ReconciliationAsOfCutoff.Standing(period.atEndOfMonth(), Instant.EPOCH, List.of(), List.of()),
                (snapshot, month) -> new PriorPeriodCorrections.Corrections(List.of(), List.of(), 0),
                (snapshot, period, revision) -> periodStore.find(snapshot, period).filter(row -> row.status() == PeriodStatus.CLOSED && row.revision() == revision)
                        .map(row -> new CloseRecordReads.CloseRecord(UUID.nameUUIDFromBytes(new byte[] {(byte) revision}), revision, row.lockedAt().orElseThrow(), UUID.nameUUIDFromBytes(new byte[] {1}), this.version.value(), UUID.nameUUIDFromBytes(new byte[] {2}), 0, 0, Instant.EPOCH,
                                Instant.EPOCH, List.of(), List.of())));
        sheet = new BalanceSheetDefinition(books, books.counterparties(), rates, notes);
        income = new IncomeStatementDefinition(books, books.counterparties(), rates, notes);
        trialBalance = new TrialBalanceDefinition(books, rates);
        int revision = periodStore.month(FEBRUARY).orElseThrow().revision();
        periodStore.markLocked(UOW, february, revision, ACCOUNTANT, Optional.of(new AccountingPeriodStore.Pin(version, 1)));
        periodStore.markCloseProposed(UOW, february, revision);
        periodStore.markClosed(UOW, february, revision);
        books.period(new TrialBalanceReads.Period(february, FEBRUARY.atDay(1), FEBRUARY.atEndOfMonth(), PeriodStatus.CLOSED, Optional.of(version)));
    }

    private static CorrelationId correlation() {
        return CorrelationId.generate(IDS);
    }

    /** What a FINAL run of {@code definition} really issues, parsed by the module's own strict reader: the same bytes a draft reads. */
    private CanonicalJson.Obj issued(ReportDefinition definition) {
        ReportRuns runs = new ReportRuns(store, periodStore, mappings, ReportDefinitions.of(sheet, income, trialBalance), ReportRuns.Leases.STANDARD, (unitOfWork, record) -> { }, (unitOfWork, envelope, payload, mediaType) -> { }, IDS, clock);
        ReportRuns.Claimed claimed = runs.claim(UOW, definition.code(), february, RunParameters.none(), ACCOUNTANT, correlation());
        ReportRunStore.RunRow held = claimed.run();
        ReportRunStore.RunRow done = runs.complete(UOW, held.id(), held.attempt(), generation.generate(UOW, definition, held.inputs()), ACCOUNTANT).run();
        assertThat(done.status()).isEqualTo(RunStatus.FINAL);
        return RunContentParser.object(store.content(UOW, done.id()).orElseThrow().text());
    }

    private static FigurePath.Figure one(CanonicalJson.Obj content, String path) {
        List<FigurePath.Figure> figures = FigurePath.of(path).resolve(content);
        assertThat(figures).as(path).hasSize(1);
        return figures.get(0);
    }

    @Test
    @DisplayName("a balance sheet: a side of the equation, a section's row and its total, one line per currency, each the amount the body wrote")
    void aBalanceSheet() {
        CanonicalJson.Obj content = issued(sheet);

        assertThat(FigurePath.of("body.equation[currency=*].assets").resolve(content)).extracting(FigurePath.Figure::currency, FigurePath.Figure::minor)
                .containsExactly(org.assertj.core.groups.Tuple.tuple("EUR", BigInteger.valueOf(2_500)), org.assertj.core.groups.Tuple.tuple("USD", BigInteger.valueOf(1_001)));
        assertThat(one(content, "body.sections[section=CASH_AND_BANK].rows[glAccount=1000,currency=EUR].closing").minor()).isEqualTo(BigInteger.valueOf(2_500));
        assertThat(one(content, "body.sections[section=CUSTOMER_FUNDS].rows[glAccount=2000,currency=USD].closing").minor()).isEqualTo(BigInteger.valueOf(1_001));
        assertThat(one(content, "body.sections[section=CASH_AND_BANK].totals[classification=ASSET,currency=EUR].closing").scale()).isEqualTo(2);
        assertThat(FigurePath.of("body.equation[currency=*].difference").resolve(content)).allSatisfy(figure -> assertThat(figure.minor()).isEqualTo(BigInteger.ZERO));
        assertThat(one(content, "body.sections[section=CASH_AND_BANK].totals[classification=ASSET,currency=EUR].closing").minor()).isEqualTo(BigInteger.valueOf(2_500));
    }

    @Test
    @DisplayName("what a statement does not hold is refused, never a zero: a currency with no row, a section naming no such row")
    void whatIsNotThereIsRefused() {
        CanonicalJson.Obj content = issued(sheet);
        assertThatThrownBy(() -> FigurePath.of("body.equation[currency=CHF].assets").resolve(content)).isInstanceOf(FigurePath.Unresolved.class);
        assertThatThrownBy(() -> FigurePath.of("body.sections[section=CASH_AND_BANK].rows[glAccount=9999,currency=EUR].closing").resolve(content)).isInstanceOf(FigurePath.Unresolved.class);
    }

    @Test
    @DisplayName("an income statement's result per currency, and a trial balance's sides per currency")
    void anIncomeStatementAndATrialBalance() {
        assertThat(FigurePath.of("body.result[currency=*].result").resolve(issued(income))).extracting(FigurePath.Figure::currency).containsExactly("EUR", "USD");

        CanonicalJson.Obj balance = issued(trialBalance);
        assertThat(FigurePath.of("body.currencies[currency=*].closingDebitBalances").resolve(balance)).extracting(FigurePath.Figure::currency).containsExactly("EUR", "USD");
        assertThat(one(balance, "body.accounts[account=1000,currency=EUR].closing").minor()).isEqualTo(BigInteger.valueOf(2_500));
        assertThat(FigurePath.of("body.currencies[currency=*].closingCreditBalances").resolve(balance)).extracting(FigurePath.Figure::currency).containsExactly("EUR", "USD");
    }

    @Test
    @DisplayName("the reader's round trip: canonical text a real definition wrote is read back to the same bytes")
    void theBytesRoundTrip() {
        CanonicalJson.Obj content = issued(sheet);
        assertThat(CanonicalJson.text(content)).isEqualTo(store.content(UOW, store.all().get(0).id()).orElseThrow().text());
    }
}
