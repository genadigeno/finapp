package com.finapp.accounting;

import static org.assertj.core.api.Assertions.assertThat;

import java.io.IOException;
import java.io.InputStream;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.util.List;
import java.util.regex.Pattern;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

/**
 * {@code accounting V014}, pinned against its text (`P14-REM-009`): the two orderings' sequence column, added expand-only and backfilled in the order release N - 1 serves. A pin proves the text; {@code RegulatorySubmissionDatabaseTest} (owed, C14) proves the orderings against
 * PostgreSQL.
 */
@DisplayName("accounting V014: the submissions' orderings on an insertion sequence (P14-REM-009)")
class RegulatoryOrderingMigrationTest {

    private static final String SUBMISSION = "accounting.regulatory_submission";
    private static final String ANSWER = "accounting.regulatory_provider_answer";

    private static String migration() {
        try (InputStream migration = RegulatoryOrderingMigrationTest.class.getClassLoader().getResourceAsStream("db/migration/accounting/V014__the_submissions_orderings_on_an_insertion_sequence.sql")) {
            if (migration == null) {
                throw new IllegalStateException("V014 is not on the test classpath");
            }
            return new String(migration.readAllBytes(), StandardCharsets.UTF_8);
        } catch (IOException e) {
            throw new UncheckedIOException(e);
        }
    }

    /** The statements, without the header's prose: a rule about what the migration does must not be satisfied or broken by what it says. */
    private static String statements() {
        return migration().replaceAll("(?m)^--.*$", "");
    }

    @Test
    @DisplayName("each table gets the column by identity, which answers N - 1's inserts and asks no grant, and from the backfill on no writer can name it")
    void theColumnIsAnIdentityNoWriterNames() {
        for (String table : List.of(SUBMISSION, ANSWER)) {
            assertThat(statements()).contains("ALTER TABLE " + table + "\n    ADD COLUMN recorded_order bigint GENERATED BY DEFAULT AS IDENTITY;");
            assertThat(statements()).contains("ALTER TABLE " + table + " ALTER COLUMN recorded_order SET GENERATED ALWAYS;");
        }
        assertThat(statements()).doesNotContain("GRANT");
    }

    @Test
    @DisplayName("the backfill is the order release N - 1 serves, stamp then id: so a cursor continues the same walk across the migration, and the numbers are the same in any copy of the rows")
    void theBackfillIsTheOrderTheLastReleaseServes() {
        assertThat(statements()).contains("SET recorded_order = numbered.place\n  FROM (SELECT id, row_number() OVER (ORDER BY prepared_at, id) AS place FROM " + SUBMISSION + ") numbered");
        assertThat(statements()).contains("SET recorded_order = numbered.place\n  FROM (SELECT id, row_number() OVER (ORDER BY received_at, id) AS place FROM " + ANSWER + ") numbered");
    }

    @Test
    @DisplayName("the identity goes ALWAYS only after the backfill, which ALWAYS would refuse, and the numbering is proven before the migration commits")
    void theOrderOfTheSteps() {
        String text = statements();
        int backfill = text.indexOf("ORDER BY received_at, id");
        int always = text.indexOf("SET GENERATED ALWAYS");
        int verified = text.indexOf("DO $$");
        int nextNumber = text.indexOf("setval(");
        assertThat(backfill).isPositive();
        assertThat(always).isGreaterThan(backfill);
        assertThat(verified).isGreaterThan(always);
        assertThat(nextNumber).isGreaterThan(text.lastIndexOf("RAISE EXCEPTION"));
    }

    @Test
    @DisplayName("each edge trigger is off for its own table's backfill alone, and back on")
    void everyTriggerIsBackOn() {
        for (String[] pair : List.of(new String[] {SUBMISSION, "regulatory_submission_permits_only_machine_edges"}, new String[] {ANSWER, "regulatory_provider_answer_is_append_only"})) {
            String off = "ALTER TABLE " + pair[0] + " DISABLE TRIGGER " + pair[1] + ";\nUPDATE " + pair[0];
            String on = "ALTER TABLE " + pair[0] + " ENABLE TRIGGER " + pair[1] + ";";
            assertThat(statements()).contains(off).contains(on);
            assertThat(statements().indexOf(on)).isGreaterThan(statements().indexOf(off));
        }
        assertThat(Pattern.compile("DISABLE TRIGGER").matcher(statements()).results().count()).isEqualTo(Pattern.compile("ENABLE TRIGGER").matcher(statements()).results().count()).isEqualTo(2);
    }

    @Test
    @DisplayName("the next number follows the backfill's last, whatever the rewrite drew; an empty table starts at one")
    void theNextNumberFollowsTheBackfill() {
        for (String table : List.of(SUBMISSION, ANSWER)) {
            assertThat(statements()).contains("(SELECT count(*) + 1 FROM " + table + "), false);");
        }
    }

    @Test
    @DisplayName("the numbering is verified row by row, and a failure says how many and carries no row's content")
    void theNumberingIsVerifiedAndCarriesNoContent() {
        String block = statements().substring(statements().indexOf("DO $$"), statements().lastIndexOf("$$;"));
        assertThat(block).contains("(ORDER BY prepared_at, id)").contains("(ORDER BY received_at, id)").contains("IS DISTINCT FROM numbered.place");
        assertThat(Pattern.compile("RAISE EXCEPTION '[^']*%[^']*', misplaced;").matcher(block).results().count()).isEqualTo(2);
        assertThat(Pattern.compile("RAISE ").matcher(block).results().count()).isEqualTo(2);
    }

    @Test
    @DisplayName("expand only: nothing a write of release N - 1 could meet, nothing destroyed, and the stamps release N - 1 orders by untouched")
    void expandOnly() {
        assertThat(statements().toUpperCase(java.util.Locale.ROOT)).doesNotContain("SET NOT NULL").doesNotContain("ADD CONSTRAINT").doesNotContain("UNIQUE").doesNotContain("CREATE TRIGGER").doesNotContain("CREATE OR REPLACE FUNCTION")
                .doesNotContain("DROP ").doesNotContain("RENAME").doesNotContain("REVOKE").doesNotContain(" TYPE ").doesNotContain("DEFAULT NEXTVAL");
        assertThat(statements()).doesNotContainPattern("(?i)SET\\s+(prepared_at|received_at)");
    }

    @Test
    @DisplayName("both orderings have the index their statements walk")
    void theIndexesAreTheStatementsOrder() {
        assertThat(statements()).contains("ON " + SUBMISSION + " (recorded_order, id);").contains("ON " + ANSWER + " (submission_id, recorded_order, id);");
    }
}
