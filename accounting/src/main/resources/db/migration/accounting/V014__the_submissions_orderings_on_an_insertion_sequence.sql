-- The regulatory submissions' two orderings, on an insertion sequence (P14-REM-009; the Phase 14 transition's G-9;
-- INV-ACC-13, INV-HIST-02; ADR-0118). This migration moves no money and judges nothing.
--
-- WHY. What stands is paged by a keyset on (prepared_at, id), and "the newest answers" are chosen by (received_at, id). Both
-- stamps are clock_timestamp(), and a database clock stepped back (an NTP step, a virtual machine's resync: measured to 2.8 s,
-- ADR-0063, PI-013) stamps a later row before an earlier one. A keyset on that order then skips or repeats a row, and "the
-- newest" names the wrong answers. A number taken at the insert cannot be reordered by any clock (lending V025, bnpl V017).
--
-- WHAT IS ADDED. recorded_order on both tables, GENERATED ALWAYS AS IDENTITY: no writer names it, and it asks no grant of the
-- application role, for whom a missing USAGE on a sequence would be a failed insert. prepared_at and received_at stay as
-- they are, stamped and served: they remain what a person is told, and release N - 1 still orders by them.
--
-- EXPAND ONLY. Nothing here can refuse a write release N - 1 makes. Its inserts do not name the column, and the identity
-- answers them. There is no SET NOT NULL (identity is NOT NULL by being identity), no CHECK, no UNIQUE and no new trigger.
-- The statements order on (recorded_order, id), so the id is the tie-break if a raw writer with OVERRIDING SYSTEM VALUE ever
-- made one, and no UNIQUE is needed to keep the keyset total. The answers' old index stays, for N - 1.
--
-- THE BACKFILL IS DETERMINISTIC. ADD COLUMN numbers the rows in whatever order the heap holds them, so each table is then
-- renumbered 1..n by exactly the order release N - 1 serves: (prepared_at, id) and (received_at, id). So a cursor (a
-- submission's id, on either release) continues the same walk across this migration, and any two copies of the same rows
-- get the same numbers. Each edge trigger is off for its table's one UPDATE alone, which it would refuse (payments V009's
-- shape); the statements are the migration's own, and nothing else can write meanwhile: ADD COLUMN holds ACCESS EXCLUSIVE to
-- this transaction's commit. The rewrite under that lock is small: a return per form and month, a few answers each. Both
-- steps are in one migration, against DATA_MIGRATIONS.md section 4.3's general rule, so that no unnumbered row ever exists
-- and one transaction is the whole of what a retry repeats. The numbering is verified row by row below; a failure raises a
-- count and carries no row's content.
--
-- WHAT A NUMBER IS NOT. It is drawn at the insert, so it is not commit order. Answers: both writers take the submission's
-- row FOR UPDATE before inserting, so for one submission the numbers are in commit order. Submissions: births of different
-- forms and months do not serialise, so a birth still uncommitted when a later number is served is missed by that walk, as
-- it was on the stamp. That is accepted: what stands is a person's worklist, a walk starts at its first page and the next
-- one serves the row in its place, the attention gauge counts the whole table, and every act judges again under its locks.
--
-- recorded_order is INTERNAL: a position, no money and no one's data.

ALTER TABLE accounting.regulatory_submission
    ADD COLUMN recorded_order bigint GENERATED BY DEFAULT AS IDENTITY;

ALTER TABLE accounting.regulatory_provider_answer
    ADD COLUMN recorded_order bigint GENERATED BY DEFAULT AS IDENTITY;

ALTER TABLE accounting.regulatory_submission DISABLE TRIGGER regulatory_submission_permits_only_machine_edges;
UPDATE accounting.regulatory_submission s
   SET recorded_order = numbered.place
  FROM (SELECT id, row_number() OVER (ORDER BY prepared_at, id) AS place FROM accounting.regulatory_submission) numbered
 WHERE numbered.id = s.id;
ALTER TABLE accounting.regulatory_submission ENABLE TRIGGER regulatory_submission_permits_only_machine_edges;

ALTER TABLE accounting.regulatory_provider_answer DISABLE TRIGGER regulatory_provider_answer_is_append_only;
UPDATE accounting.regulatory_provider_answer a
   SET recorded_order = numbered.place
  FROM (SELECT id, row_number() OVER (ORDER BY received_at, id) AS place FROM accounting.regulatory_provider_answer) numbered
 WHERE numbered.id = a.id;
ALTER TABLE accounting.regulatory_provider_answer ENABLE TRIGGER regulatory_provider_answer_is_append_only;

-- From here no writer names a number: a named value is refused, and only DEFAULT can be assigned.
ALTER TABLE accounting.regulatory_submission ALTER COLUMN recorded_order SET GENERATED ALWAYS;
ALTER TABLE accounting.regulatory_provider_answer ALTER COLUMN recorded_order SET GENERATED ALWAYS;

-- The numbering proven row by row, then the next number made to follow the last one given, however the rewrite above drew them.
DO $$
DECLARE
    misplaced bigint;
BEGIN
    SELECT count(*) INTO misplaced
      FROM (SELECT recorded_order, row_number() OVER (ORDER BY prepared_at, id) AS place FROM accounting.regulatory_submission) numbered
     WHERE numbered.recorded_order IS DISTINCT FROM numbered.place;
    IF misplaced <> 0 THEN
        RAISE EXCEPTION 'regulatory_submission: % row(s) not numbered in (prepared_at, id) order (P14-REM-009)', misplaced;
    END IF;
    SELECT count(*) INTO misplaced
      FROM (SELECT recorded_order, row_number() OVER (ORDER BY received_at, id) AS place FROM accounting.regulatory_provider_answer) numbered
     WHERE numbered.recorded_order IS DISTINCT FROM numbered.place;
    IF misplaced <> 0 THEN
        RAISE EXCEPTION 'regulatory_provider_answer: % row(s) not numbered in (received_at, id) order (P14-REM-009)', misplaced;
    END IF;
    PERFORM setval(pg_get_serial_sequence('accounting.regulatory_submission', 'recorded_order'),
                   (SELECT count(*) + 1 FROM accounting.regulatory_submission), false);
    PERFORM setval(pg_get_serial_sequence('accounting.regulatory_provider_answer', 'recorded_order'),
                   (SELECT count(*) + 1 FROM accounting.regulatory_provider_answer), false);
END;
$$;

-- What stands, a page at a time: the keyset's own order.
CREATE INDEX regulatory_submission_in_recorded_order ON accounting.regulatory_submission (recorded_order, id);
-- A submission's newest answers.
CREATE INDEX regulatory_provider_answer_in_recorded_order ON accounting.regulatory_provider_answer (submission_id, recorded_order, id);

COMMENT ON COLUMN accounting.regulatory_submission.recorded_order IS
    'The row''s place in the order the submissions were recorded in (P14-REM-009, V014): what a page of what stands is ordered by, never prepared_at, which a backward step of the database''s clock can reorder. Drawn at the insert, so not commit order. Rows before V014 numbered by (prepared_at, id).';
COMMENT ON COLUMN accounting.regulatory_provider_answer.recorded_order IS
    'The answer''s place in the order the answers were recorded in (P14-REM-009, V014): what "the newest answers" means, never received_at. Both writers hold the submission''s row FOR UPDATE, so for one submission this is also commit order. Rows before V014 numbered by (received_at, id).';
