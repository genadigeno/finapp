/**
 * Every statement of the ten, through the view a definition is really handed (`P14-TSK-017`; {@code INV-ACC-14}): the real
 * adapters and the real stores generated by the real {@link ReportGeneration} over a stand-in database, so {@code ReadOnlySnapshot}
 * screens each string and each call. That screen refuses by substring ({@code lo_}, {@code set_config}, {@code ;}), and the
 * reads of reconciliation and of the close had only ever run on a plain read-only connection: nothing else would say so before the
 * database pass. And what the ten prepare is held to reads, naming no product's schema. The statements' behaviour against
 * PostgreSQL is {@code OperationalReportsDatabaseTest}'s (owed, C5).
 */
@DisplayName("every report's statements pass the view it is handed (P14-TSK-017)")
class OperationalReportStatementsTest {

    private static final IdGenerator IDS = new IdGenerator(Clock.systemUTC(), new SecureRandom());
    private static final YearMonth MARCH = YearMonth.of(2097, 3);
    private static final Instant LOCKED_AT = Instant.parse("2097-04-05T09:00:00Z");
    private static final Instant AS_OF = Instant.parse("2097-04-05T09:30:00Z");
    private static final UUID PERIOD = IDS.next();

    private final TrialBalanceReads reads = new LedgerTrialBalanceReads(new JdbcGlMappingStore());
    private final ReconciliationMonthReads monthReads = new ReconciliationMonthReads(new JdbcReportReadings());
    private final LedgerFlooredPostings postings = new LedgerFlooredPostings();
    private final CloseRuns closeRuns = new CloseRuns(new JdbcCloseRunStore(), new JdbcAccountingPeriodStore(),
            new JdbcAccountingBreakStore(), CloseRuns.Leases.STANDARD, (uow, record) -> { }, IDS, Clock.systemUTC());

    private final ScriptedStatements script = new ScriptedStatements(sql -> {
        if (sql.contains("set_config")) {
            return List.of(row("1", "the bound"));
        }
        if (sql.equals(LedgerTrialBalanceReads.PERIOD)) {
            return List.of(row("period_start", Date.valueOf(MARCH.atDay(1)), "period_end", Date.valueOf(MARCH.atEndOfMonth()),
                    "status", "LOCKED"));
        }
        if (sql.startsWith("SELECT status, locked_at")) {
            return List.of(row("status", "LOCKED", "locked_at", Timestamp.from(LOCKED_AT)));
        }
        if (sql.startsWith("SELECT p.id, p.period_start")) {
            return List.of(row("id", PERIOD, "period_start", Date.valueOf(MARCH.atDay(1)), "status", "LOCKED", "revision", 1,
                    "opened_at", Timestamp.from(LOCKED_AT), "locked_at", Timestamp.from(LOCKED_AT)));
        }
        if (sql.startsWith("SELECT run.id, run.period_id")) {
            return List.of(row("id", IDS.next(), "period_id", PERIOD, "period_start", Date.valueOf(MARCH.atDay(1)),
                    "period_locked_at", Timestamp.from(LOCKED_AT), "period_revision", 1, "started_at", Timestamp.from(LOCKED_AT),
                    "correlation_id", "flow-1"));
        }
        return List.<Map<String, Object>>of();
    });

    @Test
    @DisplayName("the eight FINAL definitions: each generated through the view, with no statement refused")
    void theEightPassTheView() {
        for (ReportDefinition definition : List.of(new GlActivityDefinition(reads), PurposeReportDefinition.revenue(reads),
                PurposeReportDefinition.receivablesPayables(reads), PurposeReportDefinition.settlementPositions(reads),
                PurposeReportDefinition.fxResults(reads), PurposeReportDefinition.loanPortfolio(reads),
                PurposeReportDefinition.bnplExposure(reads), new SuspenseDefinition(reads, monthReads))) {
            assertThat(generate(definition, new ReportInputs(AccountingPeriodId.of(PERIOD), MARCH, 1, RunBasis.FINAL,
                    Optional.of(LOCKED_AT), Optional.empty(), Optional.empty(), LOCKED_AT, RunParameters.none())))
                    .as(definition.code()).contains("\"basis\":\"FINAL\"").contains("\"statement\":{");
        }
        assertThat(script.prepared).as("the frozen register's own read was among them")
                .anySatisfy(sql -> assertThat(sql).contains("b.raised_at < ?"));
    }

    @Test
    @DisplayName("RECONCILIATION_STATUS and CLOSE_STATUS: every store and read they reach, through the view, with no statement refused")
    void theTwoPassTheView() {
        ReportInputs live = new ReportInputs(AccountingPeriodId.of(PERIOD), MARCH, 1, RunBasis.PROVISIONAL, Optional.empty(),
                Optional.empty(), Optional.empty(), AS_OF, RunParameters.none());
        assertThat(generate(new ReconciliationStatusDefinition(new ProductReconciliationDisclosure(new JdbcReportReadings(), postings),
                monthReads, postings), live)).contains("\"basis\":\"OPERATIONAL\"").contains("\"noRun\":true");
        assertThat(generate(new CloseStatusDefinition(new AccountingCloseStatusReads(new JdbcAccountingPeriodStore(), closeRuns,
                new JdbcAccountingBreakStore(), new JdbcValuationRateSetStore()), new CloseRunStall(Duration.ofSeconds(30),
                CloseRunStall.STANDARD_POLLS)), live)).contains("\"basis\":\"OPERATIONAL\"").contains("\"runState\":\"RUNNING\"");
    }

    @Test
    @DisplayName("all of it only reads, and none of it names a product's schema: the portfolio's and the exposure's sources are the ledger's")
    void allOfItOnlyReads() {
        theEightPassTheView();
        theTwoPassTheView();
        assertThat(script.prepared).isNotEmpty().allSatisfy(sql -> {
            String upper = sql.toUpperCase(Locale.ROOT);
            assertThat(upper).startsWith("SELECT ");
            for (String forbidden : List.of("INSERT ", "UPDATE ", "DELETE ", "FOR SHARE", "FOR UPDATE", "PG_ADVISORY")) {
                assertThat(upper).as("%s in %s", forbidden, sql).doesNotContain(forbidden);
            }
            assertThat(sql).as(sql).doesNotContain("lending.").doesNotContain("bnpl.");
        });
    }

    private String generate(ReportDefinition definition, ReportInputs inputs) {
        return new ReportGeneration(ReportGeneration.FROM_THE_SNAPSHOT, Duration.ofMinutes(4), () -> 0L)
                .generate(script.connection(), definition, inputs).content();
    }
}
