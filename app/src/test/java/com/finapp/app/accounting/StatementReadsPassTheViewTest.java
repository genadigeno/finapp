/**
 * Both statements through the view a definition is really handed (`P14-TSK-016`; {@code INV-ACC-14}; the {@code OperationalReportStatementsTest} shape): the real adapters generated by the real {@link ReportGeneration} over a stand-in database, so {@code ReadOnlySnapshot} screens each string and each call -
 * that screen refuses by substring, and these reads had never been through it. What they prepare is held to reads. The statements' behaviour against PostgreSQL is {@code StatementsDatabaseTest}'s (owed, C5).
 */
@DisplayName("the statements' reads pass the view they are handed (P14-TSK-016)")
class StatementReadsPassTheViewTest {

    private static final YearMonth MARCH = YearMonth.of(2097, 3);
    private static final Instant LOCKED_AT = Instant.parse("2097-04-05T09:00:00Z");
    private static final Instant STAMP = Instant.parse("2097-04-06T09:00:00Z");
    private static final UUID PERIOD = new IdGenerator(Clock.systemUTC(), new SecureRandom()).next();
    private static final UUID CLOSE = UUID.nameUUIDFromBytes(new byte[] {2});
    private static final UUID EARLIER = UUID.nameUUIDFromBytes(new byte[] {3});
    private static final UUID RUN = UUID.nameUUIDFromBytes(new byte[] {4});
    private static final UUID VERSION = UUID.nameUUIDFromBytes(new byte[] {5});
    private static final UUID SET = UUID.nameUUIDFromBytes(new byte[] {6});
    private static final UUID ATTEMPT = UUID.nameUUIDFromBytes(new byte[] {7});

    private final TrialBalanceReads reads = new LedgerTrialBalanceReads(new JdbcGlMappingStore());
    private final CounterpartyPositionReads positions = new LedgerCounterpartyPositionReads();
    private final ValuationRateReads rates = new PinnedValuationRates(new JdbcValuationRateSetStore());
    private final StatementNotes notes = new StatementNotes(new ReconciliationMonthReads(new JdbcReportReadings(), Set.of()), new ReconciliationAsOfCutoffReads(new JdbcReportReadings()), new LedgerPriorPeriodCorrections(),
            new AccountingCloseRecordReads());

    private final ScriptedStatements script = new ScriptedStatements(sql -> {
        if (sql.contains("set_config")) {
            return List.of(row("1", "the bound"));
        }
        if (sql.equals(LedgerTrialBalanceReads.PERIOD)) {
            return List.of(row("period_start", Date.valueOf(MARCH.atDay(1)), "period_end", Date.valueOf(MARCH.atEndOfMonth()), "status", "CLOSED"));
        }
        if (sql.startsWith("SELECT status, locked_at")) {
            return List.of(row("status", "CLOSED", "locked_at", Timestamp.from(LOCKED_AT)));
        }
        if (sql.equals(AccountingCloseRecordReads.CLOSES_SQL)) {
            return List.of(row("id", CLOSE, "period_revision", 2, "period_locked_at", Timestamp.from(LOCKED_AT), "close_run_id", RUN, "pinned_mapping_version_id", VERSION, "valuation_rate_set_id", SET, "breaks_acknowledged", 3L, "breaks_resolved", 1L,
                    "proposed_at", Timestamp.from(STAMP), "decided_at", Timestamp.from(STAMP.plusSeconds(60))));
        }
        if (sql.equals(AccountingCloseRecordReads.CHECKS_SQL)) {
            return List.of(row("check_code", "RECONCILIATION_DISCLOSURE", "status", "DISCLOSED", "attempt", 2, "close_check_id", ATTEMPT, "judged_by", "reconciliation-disclosure:v2"));
        }
        return List.<Map<String, Object>>of();
    });

    @Test
    @DisplayName("both statements: generated through the view, no statement refused, every read of the notes among them; none locks, writes or names a product's schema")
    void bothPassTheView() {
        for (ReportDefinition definition : List.of(new BalanceSheetDefinition(reads, positions, rates, notes), new IncomeStatementDefinition(reads, positions, rates, notes))) {
            String content = new ReportGeneration(ReportGeneration.FROM_THE_SNAPSHOT, Duration.ofMinutes(4), () -> 0L).generate(script.connection(), definition, new ReportInputs(AccountingPeriodId.of(PERIOD), MARCH, 2, RunBasis.FINAL, Optional.of(LOCKED_AT),
                    Optional.empty(), Optional.empty(), LOCKED_AT, RunParameters.none())).content();
            assertThat(content).as(definition.code()).contains("\"basis\":\"FINAL\"").contains("\"statement\":{").contains("\"notes\":{").contains("\"acknowledgedAtProposal\":\"3\"").contains("\"disclosedChecks\":\"1\"");
        }
        assertThat(script.prepared).as("the frozen register's read").anySatisfy(sql -> assertThat(sql).contains("b.raised_at < ?"));
        assertThat(script.prepared).as("the corrections'").contains(LedgerPriorPeriodCorrections.ADJUSTMENTS_SQL, LedgerPriorPeriodCorrections.REVERSALS_SQL, LedgerPriorPeriodCorrections.ORIGIN_ENTRIES_SQL);
        assertThat(script.prepared).as("the close record's").contains(AccountingCloseRecordReads.CLOSES_SQL, AccountingCloseRecordReads.CHECKS_SQL);
        assertThat(script.prepared).isNotEmpty().allSatisfy(sql -> {
            String upper = sql.toUpperCase(Locale.ROOT);
            assertThat(upper).startsWith("SELECT ");
            for (String forbidden : List.of("INSERT ", "UPDATE ", "DELETE ", "FOR SHARE", "FOR UPDATE", "PG_ADVISORY")) {
                assertThat(upper).as("%s in %s", forbidden, sql).doesNotContain(forbidden);
            }
            assertThat(sql).as(sql).doesNotContain("lending.").doesNotContain("bnpl.");
        });
    }

    @Test
    @DisplayName("what a close record's read selects: no person, no reason, no evidence - by the statement itself, so nothing can reach a note; each statement names one schema")
    void theCloseRecordSelectsCodesCountsAndIds() {
        for (String sql : List.of(AccountingCloseRecordReads.CLOSES_SQL, AccountingCloseRecordReads.CHECKS_SQL)) {
            String lower = sql.toLowerCase(Locale.ROOT);
            assertThat(lower).doesNotContain("reason").doesNotContain("evidence").doesNotContain("proposed_by").doesNotContain("decided_by").doesNotContain("ledger.");
        }
        assertThat(AccountingCloseRecordReads.CLOSES_SQL).contains("status = 'APPROVED'").contains("period_revision <= ?").contains("ORDER BY period_revision");
    }

    @Test
    @DisplayName("the record: this revision's close, its checks, each earlier revision's close beside it, oldest first; a revision with no approved close is no record")
    void theRecord() {
        ScriptedStatements closes = new ScriptedStatements(sql -> sql.equals(AccountingCloseRecordReads.CHECKS_SQL)
                ? List.of(row("check_code", "GL_EQUALS_LEDGER", "status", "PASSED", "attempt", 1, "close_check_id", ATTEMPT, "judged_by", "gl-mapping:v1"))
                : List.of(row("id", EARLIER, "period_revision", 1, "period_locked_at", Timestamp.from(LOCKED_AT.minusSeconds(9_000)), "close_run_id", RUN, "pinned_mapping_version_id", VERSION, "valuation_rate_set_id", SET, "breaks_acknowledged", 9L, "breaks_resolved", 9L,
                                "proposed_at", Timestamp.from(STAMP.minusSeconds(9_000)), "decided_at", Timestamp.from(STAMP.minusSeconds(8_000))),
                        row("id", CLOSE, "period_revision", 2, "period_locked_at", Timestamp.from(LOCKED_AT), "close_run_id", RUN, "pinned_mapping_version_id", VERSION, "valuation_rate_set_id", SET, "breaks_acknowledged", 3L, "breaks_resolved", 1L,
                                "proposed_at", Timestamp.from(STAMP), "decided_at", Timestamp.from(STAMP.plusSeconds(60)))));
        Connection view = new ReadOnlySnapshot(closes.connection(), Duration.ofSeconds(5), () -> 0L).connection();

        CloseRecordReads.CloseRecord record = new AccountingCloseRecordReads().ofRevision(view, AccountingPeriodId.of(PERIOD), 2).orElseThrow();

        assertThat(record.close()).isEqualTo(CLOSE);
        assertThat(record.revision()).isEqualTo(2);
        assertThat(record.lockedAt()).isEqualTo(LOCKED_AT);
        assertThat(record.acknowledged()).isEqualTo(3);
        assertThat(record.resolved()).isEqualTo(1);
        assertThat(record.checks()).singleElement().satisfies(check -> {
            assertThat(check.check()).isEqualTo("GL_EQUALS_LEDGER");
            assertThat(check.attemptId()).isEqualTo(ATTEMPT);
        });
        assertThat(record.earlier()).singleElement().satisfies(earlier -> {
            assertThat(earlier.revision()).isEqualTo(1);
            assertThat(earlier.close()).isEqualTo(EARLIER);
        });
        assertThat(closes.bound).as("its period, up to its revision, then the close whose checks these are; the view's own timeout strings aside").filteredOn(value -> !(value instanceof String)).containsExactly(PERIOD, 2, CLOSE);

        ScriptedStatements none = new ScriptedStatements(sql -> List.of());
        assertThat(new AccountingCloseRecordReads().ofRevision(none.connection(), AccountingPeriodId.of(PERIOD), 2)).isEmpty();
    }

    @Test
    @DisplayName("a read that fails: thrown with its operation and SQLSTATE, never the driver's text, and never an empty record")
    void aFailedReadThrows() {
        Connection failing = (Connection) Proxy.newProxyInstance(Connection.class.getClassLoader(), new Class<?>[] {Connection.class}, (proxy, method, args) -> {
            throw new SQLException("a value the driver printed", "57014");
        });
        org.assertj.core.api.Assertions.assertThatThrownBy(() -> new AccountingCloseRecordReads().ofRevision(failing, AccountingPeriodId.of(PERIOD), 1))
                .isInstanceOf(AccountingStorageException.class).hasMessageContaining("57014").hasMessageNotContaining("a value the driver printed");
    }
}
