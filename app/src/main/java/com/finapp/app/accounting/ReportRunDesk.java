/**
 * The boundary half of the report run doors (`P14-TSK-008`; ADR-0115; {@code PHASE_14_PLAN.md} sections 10, 12; the
 * {@code AccountingPeriodDesk} shape): key every generation and regeneration per principal
 * ({@code accounting.report-run:<type>:<id>}), translate the domain's refusals onto the error contract, and audit every
 * read of a run's content before it is served.
 *
 * <p><strong>Generate</strong>: the claim runs inside the keyed transaction (T-claim) and the key's stored response is the
 * run's id - the run row is the record, so a replay answers the run as it now stands: generated by whoever holds it, or,
 * when the first flight died, taken over past its lease and generated now. A generation never returns content: content
 * is served only by the audited read. <strong>Read</strong>: the run and its content read in a read-only snapshot, the
 * read recorded {@code accounting.ReportRead} in a transaction of its own, then served - a failed record fails the read.
 * <strong>Regenerate</strong>: a FINAL run regenerated in a snapshot and compared byte for byte, the result recorded
 * {@code accounting.ReportRegenerated} under the key, a divergence counted - never repaired.
 */
@RequiredArgsConstructor
public final class ReportRunDesk {

    static final String SCOPE = "accounting.report-run:";

    static final String GENERATE_SPAN = "accounting.report.generate";
    static final String READ_SPAN = "accounting.report.read";
    static final String REGENERATE_SPAN = "accounting.report.regenerate";

    @NonNull private final ReportRuns runs;
    @NonNull private final ReportRunGenerator generator;
    @NonNull private final ReportSnapshots snapshots;
    @NonNull private final IdempotentExecutor executor;
    @NonNull private final AccountingTransactions transactions;
    @NonNull private final AccountingFlowScope flow;

    /** A run as an operator sees it - never its content, never who asked. */
    public record ReportRunView(
            String id,
            String definition,
            int definitionVersion,
            String periodId,
            String period,
            int periodRevision,
            int revision,
            String basis,
            String status,
            Integer mappingVersion,
            String valuationRateSetId,
            Map<String, String> parameters,
            String contentSha256,
            String claimedAt,
            String completedAt,
            String failure,
            String supersededAt) {}

    /**
     * A run with its content - the issued canonical JSON text, exactly the bytes {@code contentSha256} hashes, so a reader
     * can verify what it was served ({@code CONFIDENTIAL} aggregates).
     */
    public record ReportRunContentView(ReportRunView run, String content) {}

    /** A regeneration's comparison: {@code IDENTICAL} or {@code DIVERGED}, with both hashes. */
    public record ReportRegenerationView(String runId, String result, String contentSha256, String regeneratedSha256) {}

    /**
     * Claims the run answering {@code definition} for the period and parameters, and generates it when this request holds
     * it - keyed per principal; a replay answers the same run.
     */
    public ReportRunView generate(String idempotencyKey, String definition, String rawPeriodId,
            Map<String, String> parameters, String rawRateSet) {
        AccountingPeriodId periodId = periodId(rawPeriodId);
        RunParameters asked = guarded(() -> RunParameters.of(parameters, rateSet(rawRateSet)));
        Actor actor = SecurityContext.require();
        CorrelationId correlation = correlation();
        return flow.door(GENERATE_SPAN, () -> guarded(() -> {
            AtomicReference<ReportRuns.Claimed> claimed = new AtomicReference<>();
            IdempotencyKey key = new IdempotencyKey(SCOPE + actor.type().name() + ":" + actor.id(), idempotencyKey);
            RequestFingerprint fingerprint = RequestFingerprint.sha256(("generate|" + definition + "|"
                    + periodId.value() + "|" + asked.canonical()).getBytes(StandardCharsets.UTF_8));
            IdempotentExecutor.ExecutionOutcome outcome = transactions.inTransaction(unitOfWork -> executor.execute(
                    unitOfWork, key, fingerprint, uow -> {
                        ReportRuns.Claimed claim = runs.claim(uow, definition, periodId, asked, actor, correlation);
                        claimed.set(claim);
                        return CommandResult.succeeded(StoredResponse.of(
                                claim.run().id().value().toString().getBytes(StandardCharsets.UTF_8), "text/plain"));
                    }));
            ReportRunId id = ReportRunId.of(UUID.fromString(new String(outcome.body().orElseThrow(
                    () -> new IllegalStateException("a generation stores its run's id")), StandardCharsets.UTF_8)));
            ReportRuns.Claimed claim = claimed.get();
            ReportRunStore.RunRow run = claim != null && claim.mine()
                    ? generator.generateAndComplete(claim.run(), actor)
                    : generator.drive(id, actor);
            return view(run);
        }));
    }

    /** The run with its content - read in a snapshot, recorded {@code accounting.ReportRead}, then served. */
    public ReportRunContentView read(String rawRunId) {
        ReportRunId id = runId(rawRunId);
        Actor actor = SecurityContext.require();
        CorrelationId correlation = correlation();
        return flow.door(READ_SPAN, () -> {
            Served served = snapshots.read(snapshot -> new Served(
                    runs.find(snapshot, id).orElseThrow(ReportRunDesk::notFound),
                    runs.content(snapshot, id).map(ReportRunStore.Content::text).orElse(null)));
            transactions.inTransaction(unitOfWork -> {
                runs.recordRead(unitOfWork, served.run(), actor, correlation);
                return null;
            });
            return new ReportRunContentView(view(served.run()), served.content());
        });
    }

    /** What one snapshot read: the run and its content, if it has any. */
    private record Served(ReportRunStore.RunRow run, String content) {}

    /**
     * Regenerates a FINAL run and compares - keyed per principal (`P14-TSK-008`'s review, M-5: the key is looked up
     * <strong>first</strong>, so a replay answers the stored result without opening a snapshot). The platform's
     * two-transaction command: the key claimed {@code IN_PROGRESS} (Tx1), the comparison in a read-only snapshot holding no
     * transaction of the caller's, then the result and its audit record committed together (Tx2). A refusal the run itself
     * decides (not FINAL, unknown, no definition) is recorded under the key and replayed as itself; a timed-out comparison
     * records nothing - the key's lease runs out and the same key compares again. A divergence is counted once.
     */
    public ReportRegenerationView regenerate(String idempotencyKey, String rawRunId) {
        ReportRunId id = runId(rawRunId);
        Actor actor = SecurityContext.require();
        CorrelationId correlation = correlation();
        IdempotencyKey key = new IdempotencyKey(SCOPE + actor.type().name() + ":" + actor.id(), idempotencyKey);
        RequestFingerprint fingerprint = RequestFingerprint.sha256(("regenerate|" + id.value())
                .getBytes(StandardCharsets.UTF_8));
        return flow.door(REGENERATE_SPAN, () -> {
            IdempotentExecutor.BeginOutcome begun = transactions.inTransaction(
                    unitOfWork -> executor.begin(unitOfWork, key, fingerprint, claimed -> new byte[] {1}));
            if (begun.replay().isPresent()) {
                return answered(id, begun.replay().get());
            }
            ReportRunGenerator.Compared compared;
            try {
                compared = guarded(() -> generator.regenerate(id));
            } catch (ApiException refused) {
                if (refused.errorCode() != AccountingErrorCode.READ_TIMED_OUT) {
                    StoredResponse stored = StoredResponse.of((REFUSED + refused.errorCode().code())
                            .getBytes(StandardCharsets.UTF_8), "text/plain");
                    transactions.inTransaction(unitOfWork -> executor.complete(unitOfWork, key, false, stored));
                }
                throw refused;
            }
            String result = compared.identical() ? "IDENTICAL" : "DIVERGED";
            StoredResponse stored = StoredResponse.of((result + "|" + compared.run().contentSha256().orElse("") + "|"
                    + compared.regeneratedSha256()).getBytes(StandardCharsets.UTF_8), "text/plain");
            boolean recorded = transactions.inTransaction(unitOfWork -> {
                if (!executor.complete(unitOfWork, key, true, stored)) {
                    return false; // a takeover recorded first: its answer is the answer, and nothing of ours is kept
                }
                runs.recordRegeneration(unitOfWork, compared.run(), compared.identical(), actor, correlation);
                return true;
            });
            if (!recorded) {
                return answered(id, transactions.inTransaction(unitOfWork -> executor.begin(unitOfWork, key,
                        fingerprint, claimed -> new byte[] {1})).replay().orElseThrow(
                                () -> new IllegalStateException("a completed regeneration replays its result")));
            }
            if (!compared.identical()) {
                generator.diverged(compared.run());
            }
            return answered(id, stored);
        });
    }

    /** The stored answer: the result and both hashes, or the refusal recorded under the key, raised again. */
    private static ReportRegenerationView answered(ReportRunId id, StoredResponse response) {
        String body = new String(response.bodyBytes().orElseThrow(
                () -> new IllegalStateException("a regeneration stores its result")), StandardCharsets.UTF_8);
        if (body.startsWith(REFUSED)) {
            String code = body.substring(REFUSED.length());
            AccountingErrorCode refusal = java.util.Arrays.stream(AccountingErrorCode.values())
                    .filter(candidate -> candidate.code().equals(code)).findFirst()
                    .orElseThrow(() -> new IllegalStateException("a stored refusal names a known code"));
            throw new ApiException(refusal, "A report run command was refused", "the regeneration was refused.");
        }
        String[] stored = body.split("\\|", -1);
        return new ReportRegenerationView(id.value().toString(), stored[0], stored[1], stored[2]);
    }

    /** A refusal's stored prefix. */
    private static final String REFUSED = "REFUSED|";

    // ------------------------------------------------------------------ views

    static ReportRunView view(ReportRunStore.RunRow run) {
        return new ReportRunView(
                run.id().value().toString(),
                run.definition(),
                run.definitionVersion(),
                run.periodId().value().toString(),
                run.period().toString(),
                run.periodRevision(),
                run.revision(),
                run.basis().name(),
                run.status().name(),
                run.mappingVersion().orElse(null),
                run.valuationRateSetId().map(UUID::toString).orElse(null),
                run.parameters().values(),
                run.contentSha256().orElse(null),
                run.claimedAt().toString(),
                run.completedAt().map(Instant::toString).orElse(null),
                run.failure().map(Enum::name).orElse(null),
                run.supersededAt().map(Instant::toString).orElse(null));
    }

    // ------------------------------------------------------------------ plumbing

    /** The domain's refusals, in the API's words. */
    static <R> R guarded(Supplier<R> work) {
        try {
            return work.get();
        } catch (ReportRuns.DefinitionUnknown | ReportRunGenerator.DefinitionNoLongerHeld unknown) {
            throw refused(AccountingErrorCode.REPORT_DEFINITION_UNKNOWN, unknown);
        } catch (ReportRuns.ParametersInvalid | RunParameters.Invalid invalid) {
            throw refused(AccountingErrorCode.REPORT_PARAMETERS_INVALID, invalid);
        } catch (ReportRunGenerator.RunNotFinal stale) {
            throw refused(AccountingErrorCode.REPORT_RUN_STALE, stale);
        } catch (com.finapp.accounting.reporting.ReportGeneration.GenerationTimedOut timedOut) {
            throw new ApiException(AccountingErrorCode.READ_TIMED_OUT, "A report run command was refused",
                    "the regeneration did not finish within its time bound; nothing was recorded - retry.");
        } catch (AccountingPeriods.PeriodNotFound | ReportRuns.RunNotFound | ReportRunGenerator.RunNotFound unknown) {
            throw notFound();
        }
    }

    private static ApiException refused(AccountingErrorCode code, RuntimeException cause) {
        return new ApiException(code, "A report run command was refused", cause.getMessage());
    }

    private static ApiException notFound() {
        return new ApiException(AccountingErrorCode.NOT_FOUND, "No report run or accounting period answers the request",
                "no such record.");
    }

    private static AccountingPeriodId periodId(String raw) {
        try {
            return AccountingPeriodId.of(UUID.fromString(raw));
        } catch (IllegalArgumentException | NullPointerException malformed) {
            throw notFound();
        }
    }

    private static ReportRunId runId(String raw) {
        try {
            return ReportRunId.of(UUID.fromString(raw));
        } catch (IllegalArgumentException | NullPointerException malformed) {
            throw notFound();
        }
    }

    private static Optional<UUID> rateSet(String raw) {
        if (raw == null || raw.isBlank()) {
            return Optional.empty();
        }
        try {
            return Optional.of(UUID.fromString(raw));
        } catch (IllegalArgumentException malformed) {
            throw new RunParameters.Invalid("a valuation rate set is named by its id");
        }
    }

    private static CorrelationId correlation() {
        return CorrelationContext.current()
                .orElseThrow(() -> new IllegalStateException("a report run command runs inside a correlation scope"))
                .correlationId();
    }
}
