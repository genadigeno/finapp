CREATE TABLE risk.monitoring_watermark (
    source          text        NOT NULL,

    -- The exact position: the id of the last journal entry ingested (a keyset over the journal's time-ordered primary
    -- key). The floor 00000000-0000-7000-8000-000000000000 sorts before every UUIDv7 ever minted.
    last_entry_id   uuid        NOT NULL,

    -- Derived from last_entry_id by the trigger below - the id's 48-bit millisecond prefix. The application never
    -- writes it.
    last_sequence   bigint      NOT NULL,

    -- The permit: the sweep claims the row when this instant has come. Re-stamped on the database clock by the claim
    -- (now, after a full batch; the idle cadence after a short one); pulled to now by a completion hint.
    next_sweep_at   timestamptz NOT NULL,

    -- The database clock at the last change of position, stamped by the trigger.
    advanced_at     timestamptz NOT NULL,

    CONSTRAINT monitoring_watermark_pk PRIMARY KEY (source),

    -- One source today. A second source arrives by migration, with its seed row.
    CONSTRAINT monitoring_watermark_source_is_known CHECK (source IN ('ledger.journal')),

    CONSTRAINT monitoring_watermark_sequence_is_natural CHECK (last_sequence >= 0)
);

-- The 48-bit millisecond prefix of a UUIDv7, as the id generator lays it out (ADR-0013): the first twelve hex digits.
CREATE OR REPLACE FUNCTION risk.uuid7_sequence(id uuid)
    RETURNS bigint
    LANGUAGE sql
    IMMUTABLE
    STRICT
AS $$
    SELECT ('x' || substr(replace(id::text, '-', ''), 1, 12))::bit(48)::bigint;
$$;

CREATE OR REPLACE FUNCTION risk.monitoring_watermark_derives_its_sequence()
    RETURNS trigger
    LANGUAGE plpgsql
AS $$
BEGIN
    NEW.last_sequence := risk.uuid7_sequence(NEW.last_entry_id);
    IF TG_OP = 'INSERT' OR NEW.last_entry_id IS DISTINCT FROM OLD.last_entry_id THEN
        NEW.advanced_at := clock_timestamp();
    ELSE
        NEW.advanced_at := OLD.advanced_at;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER monitoring_watermark_derives_its_sequence
    BEFORE INSERT OR UPDATE ON risk.monitoring_watermark
    FOR EACH ROW
    EXECUTE FUNCTION risk.monitoring_watermark_derives_its_sequence();

-- The one source, at the floor, due now: the first sweep after this migration reads the journal from its beginning.
INSERT INTO risk.monitoring_watermark (source, last_entry_id, last_sequence, next_sweep_at, advanced_at)
VALUES ('ledger.journal', '00000000-0000-7000-8000-000000000000', 0, clock_timestamp(), clock_timestamp());

COMMENT ON TABLE risk.monitoring_watermark IS
    'The monitoring intake''s position per source - one row, the ledger journal; claimed FOR UPDATE SKIP LOCKED by the '
    'sweep (the Phase 13 lock order''s R7) and advanced in the batch''s own transaction; moved back only by an audited '
    'reprocessing order (risk.ReprocessingOrdered). A claim, not a machine (RISK_LIFECYCLES.md section 4.11).';

-- The grants: the fact table INSERT-only; the watermark's position and permit alone move; no INSERT of a source, no
-- DELETE anywhere.
GRANT SELECT, INSERT ON risk.monitored_transaction TO finapp_app;
GRANT SELECT ON risk.monitoring_watermark TO finapp_app;
GRANT UPDATE (last_entry_id, next_sweep_at) ON risk.monitoring_watermark TO finapp_app;
GRANT EXECUTE ON FUNCTION risk.uuid7_sequence(uuid) TO finapp_app;
