-- Monitored transactions and the monitoring watermark (P13-TSK-019; PHASE_13_PLAN.md sections 7.1 T-mon, 8, 12.7;
-- RISK_LIFECYCLES.md section 4.11; ADR-0111 decisions 1-4; INV-RSK-09).
--
-- THE MONITORED TRANSACTION IS BORN ONCE PER JOURNAL ENTRY, AND NEVER EDITED
--   The monitoring intake reads the ledger's journal - the one financial truth - through a port, and records exactly
--   one row per journal entry: UNIQUE (journal_entry_id) is the arbiter under ten sweepers and under any reprocessing
--   (INSERT ... ON CONFLICT DO NOTHING), so re-running the intake from an earlier watermark creates nothing new. The
--   row is INSERT-only at the privilege level (SELECT, INSERT and nothing else for the application role) and by
--   trigger for every other writer - the journal's own idiom (ledger V004). A classification the register could not
--   make is recorded as the kind UNCLASSIFIED, never skipped: nothing passes unseen (ADR-0111 decision 2), and the
--   gauge finapp.risk.monitoring.unclassified counts these rows (the alert row is P13-TSK-015's).
--
-- NEVER A BALANCE
--   amount_minor + currency + scale (the ADR-0003 three-column shape, MoneyColumns.ColumnNames.ddl() verbatim) carry
--   the entry's judged figure as seen from the subject - a movement's size, read once from the journal and never
--   summed into anything here (INV-RSK-02, PHASE_13_PLAN.md section 8).
--
-- THE WATERMARK IS A CLAIM, NOT A MACHINE
--   One row per source - the ledger journal today; a second source is a migration, which is why the application role
--   cannot INSERT here. The sweep claims the row FOR UPDATE SKIP LOCKED (the Phase 13 lock order's R7) when its permit
--   next_sweep_at has come, reads the entries after last_entry_id through the port, inserts their monitored
--   transactions and advances the watermark in the SAME transaction, so a partial batch never advances. The only
--   UPDATE the role holds is of last_entry_id and next_sweep_at: the advance, the reprocessing reset (an operator's
--   audited act moving the position BACK), and the hint (a completion handler pulling the permit forward).
--
-- WHY THE POSITION IS A UUID AND THE SEQUENCE IS DERIVED
--   The journal has no monotonic sequence column. Its entry id is a UUIDv7 (ADR-0013) whose first 48 bits are the
--   minting millisecond, and the primary key index is the journal's only ordered access path - so the intake reads
--   by id, as a keyset, and the "sequence" PHASE_13_PLAN.md speaks of is that millisecond prefix: a figure an operator
--   reads as an instant. last_sequence is DERIVED from last_entry_id by the trigger below so the two can never
--   disagree; the application never writes it. Completeness within the settle horizon the intake applies on the
--   database clock is the design's bound (DESIGN-019 section 0); the census (INV-RSK-09) is the proof.

CREATE TABLE risk.monitored_transaction (
    id                         uuid        NOT NULL,

    -- The journal entry this row was born from, by value and opaque (ADR-0029: no cross-schema foreign key). The
    -- born-once arbiter.
    journal_entry_id           uuid        NOT NULL,

    -- The entry id's 48-bit millisecond prefix - the position the intake read it at, for the eye and the lag gauge.
    journal_sequence           bigint      NOT NULL,

    entry_type                 text        NOT NULL,

    -- The posting key's namespace - everything up to and including the first ':' of the command key the ledger
    -- recorded in journal_entry.idempotency_scope, with the ledger's own prefix (ledger.post:, ledger.reverse:,
    -- ledger.adjust:) stripped by the port's implementation. The register classifies it; the value is kept so an
    -- UNCLASSIFIED row says what it saw.
    posting_namespace          text        NOT NULL,

    kind                       text        NOT NULL,

    -- The subject: the customer account or the merchant whose ledger account moved (the journal names owners by
    -- opaque reference - ledger_account.owner_kind / owner_ref); NULL for an entry with no owned side (an fx cover, a
    -- settlement batch, suspense). The party behind a customer account is resolved by the rules' task through a port,
    -- never read here.
    subject_kind               text,
    subject_ref                uuid,

    -- As seen from the subject's account: IN when it was credited, OUT when debited; NULL without a subject.
    direction                  text,

    -- The other side: the ledger's owner kind by value, its reference where it has one, and the operational purpose
    -- code where the account is the platform's own.
    counterparty_kind          text        NOT NULL,
    counterparty_ref           uuid,
    counterparty_purpose       text,

    -- The ADR-0003 three-column monetary shape, generated by MoneyColumns.ColumnNames.ddl() and pinned verbatim by
    -- RiskMigrationTest so the shape cannot drift per table. The judged figure, never a balance.
    amount_minor BIGINT NOT NULL, currency CHAR(3) NOT NULL, scale SMALLINT NOT NULL, CHECK (currency ~ '^[A-Z]{3}$'), CHECK (scale BETWEEN 0 AND 9),

    value_date                 date        NOT NULL,

    -- The entry's own created_at (the ledger's injected clock), kept so the record can be read back against the journal.
    posted_at                  timestamptz NOT NULL,

    -- The database clock at the insert, stamped by the trigger below (PHASE_13_PLAN.md section 8: every timestamp from
    -- clock_timestamp()); whatever the application supplies is overwritten.
    recorded_at                timestamptz NOT NULL,

    -- The original a REVERSAL entry compensates, by value; set exactly for a REVERSAL.
    reverses_journal_entry_id  uuid,

    CONSTRAINT monitored_transaction_pk PRIMARY KEY (id),

    -- INV-RSK-09: born once per journal entry, under ten sweepers and under any reprocessing.
    CONSTRAINT monitored_transaction_born_once UNIQUE (journal_entry_id),

    CONSTRAINT monitored_transaction_sequence_is_natural CHECK (journal_sequence >= 0),

    CONSTRAINT monitored_transaction_entry_type_is_known
        CHECK (entry_type IN ('POSTING', 'REVERSAL', 'ADJUSTMENT')),

    CONSTRAINT monitored_transaction_namespace_is_bounded CHECK (length(posting_namespace) BETWEEN 1 AND 64),

    -- The closed vocabulary MonitoredKind declares, UNCLASSIFIED among it; RiskMigrationTest holds the enum and this
    -- list to one set.
    CONSTRAINT monitored_transaction_kind_is_known CHECK (kind IN (
        'TRANSFER', 'WITHDRAWAL', 'CARD_PAYMENT', 'PAYMENT_EXECUTION', 'PAYMENT_REFUND', 'UNMATCHED_CONFIRMATION',
        'OUTBOUND_CREDIT', 'CROSS_BORDER_RETURN', 'MERCHANT_PAYOUT', 'MERCHANT_PAYOUT_RETURN', 'DISPUTE', 'SETTLEMENT',
        'RECONCILIATION_SUSPENSE', 'FX_TRADE', 'FX_COVER', 'LOAN_DISBURSEMENT', 'LOAN_REPAYMENT', 'LOAN_SERVICING',
        'LENDING_CAPITAL', 'BNPL_FINANCING', 'BNPL_REPAYMENT', 'BNPL_REFUND', 'BNPL_SERVICING', 'REVERSAL',
        'ADJUSTMENT', 'UNCLASSIFIED')),

    CONSTRAINT monitored_transaction_subject_kind_is_known
        CHECK (subject_kind IS NULL OR subject_kind IN ('ACCOUNT', 'MERCHANT')),

    CONSTRAINT monitored_transaction_subject_is_whole
        CHECK ((subject_kind IS NULL) = (subject_ref IS NULL)),

    CONSTRAINT monitored_transaction_direction_is_known
        CHECK (direction IS NULL OR direction IN ('IN', 'OUT')),

    CONSTRAINT monitored_transaction_direction_needs_a_subject
        CHECK ((subject_kind IS NULL) = (direction IS NULL)),

    CONSTRAINT monitored_transaction_counterparty_kind_is_known CHECK (counterparty_kind IN (
        'CUSTOMER', 'MERCHANT', 'LOAN', 'BNPL_OBLIGATION', 'COUNTERPARTY', 'OPERATIONAL', 'SUSPENSE', 'NONE')),

    CONSTRAINT monitored_transaction_counterparty_purpose_is_bounded
        CHECK (counterparty_purpose IS NULL OR length(counterparty_purpose) BETWEEN 1 AND 64),

    CONSTRAINT monitored_transaction_amount_is_not_negative CHECK (amount_minor >= 0),

    CONSTRAINT monitored_transaction_reversal_names_its_original
        CHECK ((entry_type = 'REVERSAL') = (reverses_journal_entry_id IS NOT NULL))
);

-- The rules' readings (P13-TSK-020): a subject's movements in a window.
CREATE INDEX monitored_transaction_by_subject
    ON risk.monitored_transaction (subject_kind, subject_ref, value_date)
    WHERE subject_kind IS NOT NULL;

-- The eye: the record in the order it was read.
CREATE INDEX monitored_transaction_by_sequence ON risk.monitored_transaction (journal_sequence);

-- The gauge finapp.risk.monitoring.unclassified counts exactly these.
CREATE INDEX monitored_transaction_unclassified
    ON risk.monitored_transaction (id)
    WHERE kind = 'UNCLASSIFIED';

-- The database clock at the insert, after the statement began - never the instance's clock.
CREATE OR REPLACE FUNCTION risk.monitored_transaction_is_stamped_by_the_database()
    RETURNS trigger
    LANGUAGE plpgsql
AS $$
BEGIN
    NEW.recorded_at := clock_timestamp();
    RETURN NEW;
END;
$$;

CREATE TRIGGER monitored_transaction_is_stamped_by_the_database
    BEFORE INSERT ON risk.monitored_transaction
    FOR EACH ROW
    EXECUTE FUNCTION risk.monitored_transaction_is_stamped_by_the_database();

-- INV-RSK-09 for the writers the grants below do not bind: a monitored row is never edited by anybody. A
-- reclassification is a reprocessing that creates nothing new, never a rewrite.
CREATE OR REPLACE FUNCTION risk.monitored_transaction_is_append_only()
    RETURNS trigger
    LANGUAGE plpgsql
AS $$
BEGIN
    RAISE EXCEPTION 'a monitored transaction is born once from its journal entry and never edited (INV-RSK-09)'
        USING ERRCODE = 'check_violation';
END;
$$;

CREATE TRIGGER monitored_transaction_is_append_only
    BEFORE UPDATE OR DELETE ON risk.monitored_transaction
    FOR EACH ROW
    EXECUTE FUNCTION risk.monitored_transaction_is_append_only();

COMMENT ON TABLE risk.monitored_transaction IS
    'The channel-neutral record of one money movement, born once per ledger journal entry (UNIQUE (journal_entry_id)) '
    'and classified by the entry''s posting-key namespace - or UNCLASSIFIED, never skipped (INV-RSK-09; ADR-0111). '
    'INSERT-only at DB-PRIVILEGE and by trigger; the judged amount of the movement, never a balance (INV-RSK-02).';

